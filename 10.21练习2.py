# 6. 双层遍历
def 打印通讯录():
    """双层遍历：外层拿人，内层拿这个人的字段"""
    for 姓名, 信息 in lianxiren.items():
        print(f"【{姓名}】")
        for 字段, 值 in 信息.items():
            print(f"  {字段}: {值}")


# ===================================================================
# 【函数封装】周五做 CLI 时，这几个函数就是菜单里的选项，直接调用
# ===================================================================

def 查询(姓名, 字段):
    """查某人的某个字段。人不在→'查无此人'；字段没填→'未填写'"""
    信息 = lianxiren.get(姓名)          # 安全查：人不在返回 None
    if 信息 is None:                     # 人不在
        return "查无此人"
    return 信息.get(字段, "未填写")       # 安全查：字段没填返回默认值


def 添加(姓名, 电话, 地址, 邮箱=""):
    """加联系人。已存在则不覆盖；邮箱可以不填（字段不统一）"""
    if 姓名 in lianxiren:                # 防覆盖：先看有没有
        return f"{姓名} 已经在通讯录里了，未覆盖"
    信息 = {"电话": 电话, "地址": 地址}
    if 邮箱:                             # 只有填了邮箱才加这个字段
        信息["邮箱"] = 邮箱
    lianxiren[姓名] = 信息               # 一次性塞进外层
    return f"已添加 {姓名}"


def 删除(姓名):
    """删联系人。人不在→'查无此人'"""
    if 姓名 not in lianxiren:
        return "查无此人"
    被删 = lianxiren.pop(姓名)           # pop 会把删掉的东西还给你
    return f"已删除 {姓名}：{被删}"


def 统计未填邮箱():
    """统计没填邮箱的人，返回 (名单, 人数)"""
    名单 = [姓名 for 姓名, 信息 in lianxiren.items() if "邮箱" not in 信息]
    return 名单, len(名单)


