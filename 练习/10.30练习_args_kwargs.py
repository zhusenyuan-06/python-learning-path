# ✅ 正确版本（思路：拼一行字符串——有则拼上、无则整段省略）：
def log(级别, 消息, *标签, **额外字段):
    """日志记录器。"""
    结果 = f"[{级别}] {消息}"                    # 前半段固定：级别 + 消息
    if 标签:                                     # 空元组 = False → 没标签整段省略
        结果 += " | 标签: " + ", ".join(标签)    # join：把元组每个元素用 ", " 连成一个字符串
    if 额外字段:                                 # 空字典 = False → 没字段整段省略
        字段列表 = []
        for k, v in 额外字段.items():
            字段列表.append(f"{k}={v}")
        结果 += " | 字段: " + ", ".join(字段列表)
    print(结果)                                  # 输出用 print，不抢 return 的活

# 测试（写完取消注释）：
