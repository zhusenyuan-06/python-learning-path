# 题目：两数之和 II —— 输入数组有序（LeetCode 167）
#
# ⚠️ 这题跟「两数之和」(LeetCode 1) 是同一道题的两种问法：
#    LeetCode 1   —— 数组【无序】，用哈希表，O(n)
#    LeetCode 167 —— 数组【升序】，用双指针，O(n)
#    题目只多了一句「输入数组已按升序排列」，但这一句直接决定了解法。
# =============================================================================
#
# ─────────────────────────────────────────────────────────────────────────────
# 【题目描述】
#
#   给定一个【升序排列】的整数数组 numbers 和一个整数 target，
#   找出数组中两个数，使它们的和为 target，返回这两个数的【下标】。
#
#   示例 1：
#       输入：numbers = [2, 7, 11, 15], target = 9
#       输出：[0, 1]
#       解释：numbers[0] + numbers[1] = 2 + 7 = 9，返回下标 0 和 1
#
#   示例 2：
#       输入：numbers = [2, 3, 4], target = 6
#       输出：[0, 2]
#       解释：numbers[0] + numbers[2] = 2 + 4 = 6
#
#   示例 3：
#       输入：numbers = [-1, 0], target = -1
#       输出：[0, 1]
#
#   ⚠️ 三个必须记住的细节：
#       ① 返回的是【下标】，不是值本身
#       ② 只要求返回【一组解】，找到就返回，不用把所有组合都列出来
#       ③ 同一个元素不能用两次（不能 numbers[i] + numbers[i]）
#
#   约束：
#       - numbers 长度 2 ~ 50000
#       - numbers 严格升序
#       - 元素可能是负数、0、正数
#
# ─────────────────────────────────────────────────────────────────────────────
# 【先想这三个问题，再动手写】← 答案写在下面「我的思考」区
#
#   Q1. 双指针为什么能成立？它靠的是什么前提？
#       （提示：不是"左边的数小"，而是"在【当前区间】里 left 最小、right 最大"）
#
#   Q2. 为什么循环条件写 while left < right，不写 <= ？
#       （提示：left == right 时会发生什么？题目允许吗？）
#
#   Q3. 如果 numbers 变成【无序】的，这个方法还成立吗？为什么？
#       （提示：举一个数组，写出双指针会【漏掉】的那组解）
#
