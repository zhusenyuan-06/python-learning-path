# 【第 3 站】⭐⭐ 最重要的概念：__name__ 与程序入口
# ============================================================
#
# 每个 Python 文件都有一个内置变量 __name__：
#   - 直接运行这个文件     → __name__ == "__main__"
#   - 被别的文件 import   → __name__ == "模块自己的名字"
#
# 这就是下面这个惯用法的全部原理：
#
#     def main():
#         print("我是主程序")
#
#     if __name__ == "__main__":
#         main()
#
# 为什么需要它？
#   想象：一个「工具模块」里面写了测试代码。
#   别人 import 它时，测试代码不该跟着跑。
#   用 if __name__ == "__main__" 包起来 → 只有直接运行时才跑测试。
#
