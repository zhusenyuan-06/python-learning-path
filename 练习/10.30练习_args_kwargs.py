# 第 2 题 · 为什么 * 和 ** 在【定义处】和【调用处】含义不同？
# ============================================================
# 这题是今天【最核心】的一题。
# * 在两个位置是两回事：
#   · 定义处  *args  = 「把多出来的位置参数【打包】成元组」
#   · 调用处  *列表   = 「把列表【拆开】成一个个位置参数」
# ** 同理：
#   · 定义处  **kwargs = 「把多出来的关键字参数【打包】成字典」
#   · 调用处  **字典   = 「把字典【拆开】成一个个关键字参数」
