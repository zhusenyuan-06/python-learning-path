# =============================================================================
# 【我的思考】（11-04 讲解后整理；复习时可以自己再写一遍）
#
# Q1. 双指针为什么能成立？前提是什么？
#     → 前提是【数组升序】。
#     → left 指向当前区间 [left..right] 里的【最小值】，right 指向当前区间的【最大值】。
#       ⚠️ 注意是「当前区间」，不是「整个数组」—— 指针会走，首尾属性会变。
#     → 每算一次和，就知道该动哪个指针：
#         和 > target → 和太大 → right 左移（换小一点的）
#         和 < target → 和太小 → left 右移（换大一点的）
#       每次移动都排除掉一整行/一整列，所以总共只走 n 步 → O(n)。
#
# Q2. 为什么是 while left < right，不是 <= ？
#     → left == right 时意味着【自己跟自己配】：numbers[left] + numbers[right]
#       是同一个数加了两遍。题目规定一个元素只能用一次，所以这种情况非法。
#     → 实测：[3], target=6 时，写 <= 的版本会返回 [0, 0]（3+3=6），
#       正确答案是 []。所以必须用 <。
#     → 区分两个词：while left < right = 还没相遇，搜索继续；
#                   left == right  = 相遇了，搜索结束。
#
# Q3. 数组无序的话还成立吗？
#     → 不成立。
#     → 因为前提（区间最小/最大）没了。right 不一定是最大值，left 也不一定是最小值，
#       「和 > target 就该 right 左移」这个推理直接失效，会漏解。
#     → 实锤反例：[1, 10, 2, 5], target = 7
#           双指针（按升序假设跑）→ []        ← 漏了
#           暴力（真遍历）      → [2, 3]     ← 值 2 + 值 5 = 7
#     → 所以 LeetCode 1（无序）必须用哈希表，167（有序）才能用双指针。
#
# ─────────────────────────────────────────────────────────────────────────────
# 【我的额外发现】
#
#   「双指针没有 for 循环，找到一组就 return，函数是不是就结束了？」
#     → 是的，完全正确。LeetCode 167 只要求返回【一组解】，所以找到就 return。
#     → 这正是双指针能赢的地方：
#           暴力版 O(n²)：所有 (i, j) 组合都要试一遍
#           双指针 O(n)  ：每步排除一整行/一整列，只走 n 步
#         数组长度 200 时，差 100 倍。
#     → ⚠️ 但这个 early-return 有前提：被排除掉的那一行/一列确实【不可能】有解
#       （这来自「数组升序」）。如果题目改成「返回所有解」，
#       双指针就不能找到就停，得在 == target 时继续往下搜。
#
# =============================================================================


# =============================================================================
# 【版本 A · 双循环暴力】（对照组，用来验证双指针没漏解）
#
#   思路：
#       外层 for 固定【小的那个下标】i
#       内层 for 从 i+1 开始往后找 j（因为 i+1..end 只会越来越大）
#       一旦找到 numbers[i] + numbers[j] == target，立刻返回
#
#   为什么不重不漏：
#       - 内层从 i+1 开始 → 同一个元素不会跟自己配
#       - 每个 (i, j) 组合只被访问一次 → 不重复
#       - 所有 i 都试过了 → 不遗漏
#
#   ⚠️ 版本 A 和版本 B 在【有多组解】时，返回的下标【可能不同】！
#      两边都是对的，只是选了一组不同的解。
#      所以对照测试要比的是「有没有解」和「解对不对」，不是「下标一不一样」。
#      这也是下面自测区里分两种判定方式的原因。
# =============================================================================
def two_sum_slow(numbers, target):
    """暴力版：双循环找和为 target 的两个数，返回下标列表；找不到返回 []。

    参数：
        numbers —— 升序排列的整数列表
        target  —— 目标和
    返回：
        [i, j]  —— 一组解的下标（i < j）；找不到返回 []
    """
    for i in range(len(numbers)):              # 逐行 ①：外层循环，定住「小的那个下标」i
        for j in range(i + 1, len(numbers)):    # 逐行 ②：内层循环，从 i+1 开始（不能自己跟自己配）
            if numbers[i] + numbers[j] == target:   # 逐行 ③：这一对加起来是不是 target
                return [i, j]                  # 逐行 ④：找到了，立刻返回一组解
    return []                                  # 逐行 ⑤：所有组合都试过了，没有解


# =============================================================================
# 【版本 B · 双指针】（优化版，O(n)）
#
#   ⚠️ 这段是【你 11-04 自己写的】，我只做了两件事：
#      ① 把你原来的行尾注释改成【逐行注释】（你的原话注释保留在后面）
#      ② 补上 docstring（原来只有一行）
#
#   ⚠️ 你 11-04 踩过的一个坑记在这里：第一次写的时候
#      left = 0 是 4 空格、right = ... 是 8 空格，两行不齐 → IndentationError。
#      缩进在 Python 里是【层级栈】，不是「对齐好看」，必须一层一层严格递进。
#
#   ⚠️ 复习时请把上面版本 A 的函数体【先注释掉】，自己从零敲一遍版本 B，
#      敲完再打开对照。要想起来的三个点：
#       ① right 的初值必须用 len(numbers) - 1 算，不能写死
#       ② 循环必须是 while 不是 if（if 只走一步就出函数了）
#       ③ 找不到要 return []，不能 return None，也不能 print
# =============================================================================
def two_sum_sorted(numbers, target):
    """返回和为 target 的两个数的下标列表；找不到返回 []。

    参数：
        numbers —— 升序排列的整数列表
        target  —— 目标和
    返回：
        [i, j]  —— 一组解的下标（i < j）；找不到返回 []
    """
    # ↓↓↓ 你的代码 ↓↓↓
    left = 0                            # 逐行 ①：left 从最左边出发
    right = len(numbers) - 1            # 逐行 ②：right 从最右边出发（用 len 算，别写死）
    while left < right:                 # 逐行 ③：还没相遇就继续（用 < 不用 <=，见「我的思考」Q2）
        和 = numbers[left] + numbers[right]     # 逐行 ④：当前区间两端的和
        if 和 == target:                # 逐行 ⑤：正好等于 → 找到一组解
            return [left, right]        # 逐行 ⑥：返回下标（不是值）；题目只要一组，可以直接结束
        elif 和 > target:               # 逐行 ⑦：和太大 → 需要换小一点的 → right 左移
            right -= 1
        else:                           # 逐行 ⑧：和太小 → 需要换大一点的 → left 右移
            left += 1
    return []                           # 逐行 ⑨：left 追上 right（相遇），说明区间里没有解


