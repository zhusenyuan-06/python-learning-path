# ============================================================
# 【第 2 站】import 的 4 种写法（已练过，这里只记结论）
# ============================================================
#
# | 写法                      | 拿到的名字            | 什么时候报错      |
# |--------------------------|----------------------|-------------------|
# | import 模块               | 模块名                | 模块名错→立刻     |
# | from 模块 import 函数      | 函数名（直接可用）      | 函数名错→立刻     |
# | import 模块 as 别名        | 别名                  | 模块名错→立刻     |
# | from 模块 import *        | 模块内所有名字           | 用错名字→运行时   |
#
# ⭐ 报错时机规律（今天最重要的收获）：
#   「from ... import 名字」→ 名字写错 = 立刻报错（ImportError）
#   「import 模块」后调用    → 名字写错 = 运行到才报错（AttributeError）
#
