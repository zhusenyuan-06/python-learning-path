def 取返回值(函数名, *参数):
    """调用你写的函数，取它的 return 值。

    如果你：① 没写代码 ② 没 return ③ 报错了
    这里都会给出明确提示，而不是假装通过。
    """
    try:
        返回值 = 函数名(*参数)
    except NotImplementedError:
        return False, "❌ 还没写（函数体还是 pass）"
    except Exception as e:
        return False, "❌ 报错 → %s: %s" % (type(e).__name__, e)
    if 返回值 is None:
        return False, "❌ 函数没有 return（print 不算数，检查读的是 return 值）"
    return True, 返回值


def 检查(题号, 名称, 实际, 期望, 判定=None):
    """比对实际值与期望值。判定函数不传时用 == 直接比。"""
    if 判定 is None:
        判定 = lambda a, b: a == b
    if 实际 is False and isinstance(期望, str) and 期望.startswith("❌"):
        print("❌ 第 %s 题 · %-14s %s" % (题号, 名称, 实际))
        return False
    通过 = 判定(实际, 期望)
    if 通过:
        print("✅ 第 %s 题 · %-14s 通过" % (题号, 名称))
    else:
        print("❌ 第 %s 题 · %-14s" % (题号, 名称))
        print("      你返回的：%r" % (实际,))
        print("      期望的：  %r" % (期望,))
    return 通过


