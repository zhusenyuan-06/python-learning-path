class Solution_你的第一版:
    """你的第一版。跑起来会报 TypeError —— 这就是它的价值。"""

    def isAnagram(self, s: str, t: str) -> bool:
        d = {}                        # ① 一个字典，s 和 t 共用
        for ch in s:
            d[ch] = d.get(ch, 0) + 1  # ② 遍历 s：加一
        for ch in t:
            d[ch] = d.get(ch, 0) - 1  # ③ 遍历 t：减一
            if ch <= -1:              # ❌ 错误1：判断的是【字符】不是【计数】
                return False           #    ch 是 str，跟 int 比 → TypeError
            # ⑤ 这里少了最终判定
        if d.values():                # ❌ 错误2：values() 是视图对象，永远为真！
            return True               #    → 这题会永远返回 True，静默错
        return False


