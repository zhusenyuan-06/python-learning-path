def 统计词频(文章列表):
    """统计每个词出现次数，返回字典。⚠️ 这版有 bug，结果是错的。"""
    词频 = {}                                  # ← 词频 先当【字典】用
    for 文章 in 文章列表:
        for 词 in 文章.split():
            if 词 not in 词频:
                词频[词] = 0
            词频[词] += 1
    词频 = len(词频)                           # ← 词频 后又当【整数】用
    return 词频


文章们 = ["我爱北京天安门", "天安门在北京", "北京天安门"]
结果 = 统计词频(文章们)
