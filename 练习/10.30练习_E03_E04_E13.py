#    ③ 解法：用正则按「连续汉字块 / 连续英文数字块」切（见下面的 re 版）：
import re

def 词频统计_re(文本, n=3):
    """真正能处理连续中文的词频统计器。"""
    counts = {}
    for w in re.findall(r'[一-鿿]+|[A-Za-z0-9]+', 文本):
        w = w.lower().strip(".,!?，。！？")
        if not w:
            continue
        if w in 停用词:
            continue
        counts[w] = counts.get(w, 0) + 1
    return sorted(counts.items(), key=lambda x: x[1], reverse=True)[:n]

