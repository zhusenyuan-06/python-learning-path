#
# Q1. 异位词跟「完全相同」差在哪？
#     → 异位词只看【每个字符的出现次数】，不看顺序。
#       "anagram" 和 "nagaram" 是异位词（顺序不同，但字母个数完全一样）。
#
#     ⚠️ 完全相同【一定是】异位词（完全相同是异位词的子集）。
#       所以「完全相同但不是异位词」的反例【不存在】——这题我第一次出错了，
#       真正的反例应该是「顺序一样但不是异位词」：比如 "abc" vs "abd"。
#
# Q2. 一个 dict 怎么判定？
#     → 因为「异位词 = 每个字符出现次数都相同」，
#       所以把 s 和 t 的计数【放进同一个字典】，一个加一个减：
#         遍历 s：d[ch] = d.get(ch, 0) + 1     ← 加一
#         遍历 t：d[ch] = d.get(ch, 0) - 1     ← 减一
#       走完之后，字典里每个值【都该是 0】—— 因为同一个字符在两边的次数
#       一样时，加一减一正好抵消。
#       → 判定：all(v == 0 for v in d.values())
#
#     提前返回的时机：只能在【减一】那半边判断。
#       一旦某个计数变成【负数】，说明 t 里有 s 完全没有的字符 → 立刻 False。
#       实测：s="abc" t="abd" → 减到 'd' 时 d['d'] = -1 → 第 2 步就能返回。
#
#     ⚠️ 能不能在遍历 s 的过程中就查「有没有全 0」？【不能】
#       因为 s 加完时每个字符的计数都是【正数】（至少 1），根本不可能全 0。
#       实测：s 只加完第 1 个字符 → {'a': 1} → 全是 0 吗？False。
#       → 这就是「在错误的时机检查」= 静默错误（E15 家族的病）。
#
# Q3. 「只包含小写字母」这个约束为什么重要？
#     → 因为它保证了「ord(ch) - ord('a')」算出来的下标【一定落在 0~25】，
#       所以「26 格数组」这个方案才成立。
#
#       去掉这个约束，26 格数组会怎样？（全部实测过）
#         字符 'a'  → 下标   0  → 正常
#         字符 'A'  → 下标 -32  → IndexError: list index out of range（崩溃，看得见）
#         字符 '中'  → 下标 19916 → IndexError: list index out of range（崩溃，看得见）
#         字符 'Z'  → 下标  -7  → 【不报错！】静默写到数组尾部倒数第 8 格 ← 最阴
#
#       → 大写字母的「崩溃」反而是好事（看得见）；
#         真正可怕的是 'Z' 这种【负下标】——Python 允许负下标，
#           结果错得莫名其妙，全程零报错。
