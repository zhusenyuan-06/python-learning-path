# 我的回答（11-14 晚 AI 代填 · 闭卷答案 + 出处）：
#
# ① re.search 找不到时返回 None。
#    直接 .group() 会报 AttributeError: 'NoneType' object has no attribute 'group'
#    ★ 今天下午任务 1-③ 就是这么崩的 —— 同一个坑，已登记 E42。
#    所以永远是：m = re.search(...); if m: m.group()
#
# ② re.findall(r"a*", "bbb") 返回 ['', '', '', ''] —— 四个【空字符串】。
#    因为 * 是「0 次或多次」，在每个位置都能匹配「0 个 a」。
#    ⚠️ 空串的个数 = 字符串长度 + 1（"bbb" 长度 3 → 4 个位置：开头、b、b、b、末尾）
#    讲义里那个 r'a*' 配 "bb" 的例子是 3 个（长度 2 + 1），别记混。
#    想「至少 1 次」就用 + 或 {1,}（讲义第九节坑1）。
#
# ③ 返回类型是【列表】['123']。
#    ⚠️ 但要记住 findall 的返回规则：
#      · 模式里没有捕获组 → 返回【整个匹配】的字符串列表
#      · 模式里有 1 个捕获组 → 返回【那 1 个组】的内容列表
#      · 模式里有 N 个捕获组 → 返回【元组】列表（每组一个元素）
#    这里 (\d+) 正好吃掉了全部内容，所以组内容 = 整个匹配，看不出差别；
#    但任务 4-① 的 (\d{4})-(\d{2})-(\d{2}) 就返回了 [('2026','11','14')]。
#
# ④ $ 匹配的是【行尾】（每一行的末尾都算它），
#    \Z 匹配的是【整个字符串的末尾】。
#    实测：re.search(r"\w+$", "hello\n") → 'hello'   （第一行的行尾）
#         re.search(r"\w+\Z", "hello\n") → None     （末尾是换行符，\Z 找不到）
#    要「整个字符串必须长这样」，最省心的是 re.fullmatch()（讲义第九节坑2）。
