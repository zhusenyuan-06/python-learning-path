def 任务1_筛选单条件():
    """筛选出【星期二】的所有行。

    返回：(条数, 序号列表)
      条数     → int，筛选出的行数
      序号列表 → list，筛选出的「序号」列，从小到大
    """
    # TODO 1-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    选中 = df[df['星期'] == '星期二']  # ← ② 填筛选条件
    return len(选中), list(选中['序号'])  # ← ③ 条数、序号列表


def 任务2_筛选多条件():
    """筛选出【星期 == '星期一'】并且【序号 > 5】的行。

    返回：序号列表（从小到大）
    """
    # TODO 2-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    选中2 = df[(df['星期'] == '星期一') & (df['序号'] > 5)]
    return list(选中2['序号'])


def 任务3_筛选关键词():
    """筛选出【新闻内容】里含有「银行」或含有「雨雪」的行。

    返回：序号列表（从小到大）
    """
    # TODO 3-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    选中3 = df[df['新闻内容'].str.contains('银行') | df['新闻内容'].str.contains('雨雪')]
    # ⚠️ 本次是【蒙对】：「银行」「雨雪」不含正则元字符，所以没出事。
    #    str.contains 默认走【正则】，'.' = 任意字符。实测本表：
    #      str.contains('1.')            → 4 行（"10 月""120 人""16 日"全被匹配）
    #      str.contains('1.', regex=False) → 1 行（真·字面量）
    #    稳妥写法：两个关键词都加 regex=False
    return list(选中3['序号'])


def 任务4_筛选后统计():
    """筛选出【序号 <= 10】的行，然后统计。

    返回：(最大序号, 条数)
      最大序号 → int，这批行里最大的「序号」
      条数     → int，这批行有多少行
    """
    # TODO 4-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    df.sort_values(by='序号', ascending=False)   # ← ⚠️ 哑弹！返回值没接住，这行等于没写
    选中4 = df[df['序号'] <= 10]
    #    实测：sort_values 默认【返回新表】不改原表，所以这里顺序根本没变。
    #    正确写法：df = df.sort_values(by='序号', ascending=False)
    #    而且本题只要 max 和 len，跟顺序无关 —— 这行本来就不必要。
    return max(list(选中4['序号'])),len(list(选中4['序号']))
    #    ↑ 能用但绕了两圈。标准写法：
    #    return int(选中4['序号'].max()), len(选中4)



def 任务5_新增数值列():
    """新增一列【双倍序号】= 序号 × 2。

    返回：新列的前 3 个值（list）
    """
    # TODO 5-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    df['双倍序号'] = df['序号'] * 2
    return list(df['双倍序号'].head(3))


def 任务6_新增字符串列():
    """新增一列【标签】= 星期 + '-' + 序号  （例如 '星期六-1'）。

    返回：新列的前 3 个值（list）
    """
    # TODO 6-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    df['标签'] = df['星期'] + '-' + df['序号'].astype(str)
    return list(df['标签'].head(3))



def 任务7_删除列():
    """删掉【新闻内容】这一列。

    返回：删完之后剩下的列名（list）
    """
    # TODO 7-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    选中7 = df.drop(columns=['新闻内容'])
    return list(选中7.head(0))   # ← 结果对，但 head(0) 是多余的：list(选中7) 给的也是列名
    #    标准写法：return list(选中7.columns)


def 任务8_重命名列():
    """把【序号】这一列改名为【编号】。

    返回：改完之后所有列名（list）
    """
    # TODO 8-① 在下面写你的代码
    df = pd.read_csv(CSV路径)
    选中8 = df.rename(columns={'序号': '编号'})
    return list(选中8.head(0))   # ← 同上，标准写法：return list(选中8.columns)


