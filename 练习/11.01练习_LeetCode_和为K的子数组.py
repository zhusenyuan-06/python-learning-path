#
# Q1: 数组里可能有负数，说明什么？
#     → 有负数就不能用滑动窗口。滑动窗口成立的前提是「和单调不减」，
#       窗口才能只往一个方向滑。有负数时和会忽大忽小，滑不动。
#       → 这是本题必须用「前缀和 + 字典」的原因。
#
# Q2: 「和为 k 的子数组个数」——不用「算每个子数组的和」这个笨办法，
#     还能怎么数？
#     → 固定右端点，往前数。对每个位置 j，问「以 j 结尾、和为 k 的子数组
#       有几个」→ 这就等于「前面有多少个前缀和 = P[j+1] - k」。
#       用字典记住每个前缀和出现几次，一次查询就得到答案。
#
# Q3: 你打算用几个字典？每个字典的 key 存什么？
#     → 一个。key = 前缀和的值，value = 它出现过几次。
