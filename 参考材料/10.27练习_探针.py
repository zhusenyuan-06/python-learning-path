# 探针脚本：不是答案，是 X 光片
# 目的：让你亲眼看见 *args 和 **kwargs 到底装了什么

def 探针(园所名, *菜单, **附加):
    print("【园所名】=", repr(园所名))
    print("【菜单】  =", repr(菜单))
    print("【附加】  =", repr(附加))
    print("菜单一共有", len(菜单), "项")


print("===== 调用一次，看看抽屉里是什么 =====")
