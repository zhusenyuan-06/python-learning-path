#   ...   ...           ...                 ...
#   15    2026-11-23    五国及欧盟机构...     星期一
#
# 星期分布（可作为筛选对象）：
#   星期一 3 条 | 星期二 2 条 | 星期三 1 条 | 星期四 1 条
#   星期五 2 条 | 星期六 4 条 | 星期日 2 条
