target = Path("输出") / "文件清单.txt"
# ✅ 用 / 运算符拼路径（Path("输出") / "文件清单.txt"），不要用 + 拼字符串
# 好处：路径全程是【对象】，不会出现斜杠方向混乱、少斜杠的坑
target.parent.mkdir(parents=True, exist_ok=True)
# .parent = 取父目录（这里是 输出/）
# mkdir(parents=True) = 父目录不存在也一起建；exist_ok=True = 目录已存在也不报错

# ① 先把内容攒成字符串（每行一个文件）
内容 = ""                      # 空的字符串
# 内容 = "" = 先准备一个空字符串当"容器"
for f in p.glob("*练习*.py"):
    # 再遍历一次要写进清单的文件
    内容 += f"{f.name}  {f.stat().st_size}\n"    # 用 += 累加
    # f"..." 是 f-string，可以把 {表达式} 直接嵌进字符串
    # 每行格式：文件名 + 两个空格 + 字节数 + \n 换行符
    # += 是字符串累加（注意：循环里大量 += 字符串会慢，但这里只有 18 个，无所谓）

# ② 再用 open 写进去，路径直接用 pathlib 的对象
with open(target, "w", encoding="utf-8") as fp:
    # ✅ 重点：open() 的路径参数【可以直接吃 pathlib 对象】，不用转成字符串
    # 这就是 pathlib 的核心好处：路径全程是对象，告别字符串拼接的坑
    fp.write(内容)
    # 把攒好的整段内容一次写进文件


