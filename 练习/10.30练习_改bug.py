def 统计词频_错版(文本):
    """❌ 有 bug 的版本。"""
    words = 文本.split()
    counts = {}
    for w in words:
        w = w.lower()                       # ← 坑 1：只 lower，没 strip
        counts[w] = counts.get(w, 0) + 1
    return counts


