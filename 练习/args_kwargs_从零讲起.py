print("===== 第 1 步：最朴素的函数 —— 参数个数写死 =====")


def 加两个(a, b):
    return a + b


print("  加两个(3, 4) =", 加两个(3, 4))
print("  问题：如果我想加 5 个数呢？")


print()
print("===== 第 2 步：办法一 —— 把签名拉长 =====")


def 加五个(a, b, c, d, e):
    return a + b + c + d + e


print("  加五个(1,2,3,4,5) =", 加五个(1, 2, 3, 4, 5))
print("  但现在只能加 5 个。加 3 个：")
try:
    加五个(1, 2, 3)
except TypeError as e:
    print("     报错 ->", e)
print("  加 6 个：")
try:
    加五个(1, 2, 3, 4, 5, 6)
except TypeError as e:
    print("     报错 ->", e)
print("  问题：个数一变，签名就得重写。")


print()
print("===== 第 3 步：办法二 —— 让调用方自己包成列表 =====")


def 加一组(数字们):
    return sum(数字们)


print("  加一组([3,4,5]) =", 加一组([3, 4, 5]))
print("  问题1：调用时必须自己包一层方括号")
print("  问题2：只能收「按位置」的东西。带名字的传不进来：")
try:
    加一组([3, 4, 5], 名称="三月")
except TypeError as e:
    print("     报错 ->", e)


print()
print("===== 第 4 步：办法三 —— *args，让 Python 帮你打包 =====")


def 加任意个(*数字):
    return sum(数字)


print("  加任意个(3,4,5) =", 加任意个(3, 4, 5))
print("  加任意个(3,4,5,6,7,8,9) =", 加任意个(3, 4, 5, 6, 7, 8, 9))
print("  加任意个(3) =", 加任意个(3))
print("  加任意个() =", 加任意个())
print("  不用包方括号了。看函数里到底收到什么：")


def 看(*数字):
    print("     数字 =", repr(数字), "  类型:", type(数字).__name__)
    print("     数字[0] =", 数字[0], "   数字[1] =", 数字[1])


看(3, 4, 5)


print()
print("===== 第 5 步：为什么还要再来一个 ** =====")
print("  试试给「带名字」的实参：")
try:
    加任意个(3, 4, 5, 名称="三月")
except TypeError as e:
    print("     报错 ->", e)
print("  因为 *args 只收【按位置】的实参。加一个 **kwargs 才收【带名字】的：")


def 加任意个2(*数字, **备注):
    print("     数字 =", 数字, " | 备注 =", 备注)


加任意个2(3, 4, 5, 名称="三月", 出处="第一班")


print()
print("===== 第 6 步：四个形参各管各的 =====")


def 全都(a=0, b=0, *args, **kwargs):
    print("     a =", a, "| b =", b)
    print("     args =", args)
    print("     kwargs =", kwargs)


print("  情况1：正好 2 个位置参数，没有多余的")
全都(1, 2)
print("  情况2：2 个固定 + 2 个多余位置 + 1 个关键字")
全都(1, 2, 3, 4, 名称="张三")
print("  情况3：只给关键字，a 和 b 用了默认值")
全都(名称="张三")


print()
print("===== 第 7 步：反方向 —— 调用处的拆包 =====")


def 收(a, b, *args, **kwargs):
    print("     a =", a, "| b =", b, "| args =", args, "| kwargs =", kwargs)


数字们 = [3, 4, 5]
备注们 = {"名称": "张三", "出处": "第一班"}
print("  不拆（直接把容器当普通参数传）：")
收(1, 2, 数字们, 备注们)
print("  用 * 拆列表：")
收(1, 2, *数字们)
print("  用 * 拆列表 + ** 拆字典：")
收(1, 2, *数字们, **备注们)
print("  ↑ 这一行完全等价于：收(1, 2, 3, 4, 5, 名称='张三', 出处='第一班')")


print()
print("===== 第 8 步：*args 真正不可替代的地方 =====")


def 打印所有(*内容, **选项):
    """把收到的东西原样转交给内置 print"""
    print(*内容, **选项)


打印所有("一", "二", "三")
打印所有("一", "二", sep="-")
打印所有("一", "二", end="")
print("   <- 上面 end 吃掉了换行")
print("  不写 *args / **kwargs，你根本写不出能接受任意参数的 print 包装器")


print()
print("===== 第 9 步：规律 —— 实参有几个，元素就有几个 =====")


def 看2(*数字):
    print("     元组 =", 数字, "  元素个数 =", len(数字))


print("  看2([1,2,3])        —— 实参 1 个（一个列表）")
看2([1, 2, 3])
print("  看2(1,2,3)          —— 实参 3 个")
看2(1, 2, 3)
print("  看2(*[1,2,3])       —— * 把列表拆成 3 个实参")
看2(*[1, 2, 3])
print("  看2([[1],[2],[3]])  —— 实参 1 个（列表套列表）")
看2([[1], [2], [3]])
print("  看2(*[[1],[2],[3]]) —— * 拆成 3 个实参，每个都是列表")
看2(*[[1], [2], [3]])
print("  规律：元组长度 == 实参个数。* 改变的就是「实参有几个」。")
