# ---- 导入的标准库（每个都要有中文注释）----
import argparse                     # 命令行参数解析（位置参数 / --top / --help）
import re                           # 正则表达式（用来切中英文词）
import sys                          # sys.exit() 用来以指定退出码结束程序
from pathlib import Path            # 路径对象（exists() 判断文件在不在）

# =============================================================================
# 【切词用的正则】
#
#   [\u4e00-\u9fa5]+   连续的中文汉字
#                     \u4e00 = "一" 的 Unicode 码位，\u9fa5 = "龥" 的码位
#                     中文字符在 Unicode 里集中在这个连续区间
#                     +  表示「前面的东西出现 1 次或多次」（贪婪匹配）
#
#   [a-zA-Z]+         连续的英文字母（不分大小写地收进来）
#
#   |                 或者 —— 两种都匹配，谁先谁后都行
#
#   整行的意思：「要么是一串汉字，要么是一串字母，挨着的一起收」
#
#   ⚠️ 这个正则【不处理数字】。所以 "2024年" 会被切成 ["年"]，
#      "iphone15" 会被切成 ["iphone"]。这是刻意的取舍，见「已知限制」。
# =============================================================================
词模式 = re.compile(r'[\u4e00-\u9fa5]+|[a-zA-Z]+')


# =============================================================================
# 【核心 1】切词
# =============================================================================
def 切词(文本):
    """把一段文本切成词列表。
    要求：
      ① 用上面的 词模式 找出所有词
      ② 【把空串滤掉】
         —— 为什么必须滤？见 Q2，实测例子："apple , . banana"
            → 切完会得到 ['apple', '', '', 'banana']
            → 空串会被当成一个"词"计数，还可能排进 top N！

    用到的 API：
      词模式.findall(文本)   → 返回所有匹配到的字符串组成的列表
      [w for w in ... if w]  → 列表推导式 + 过滤（if w 会滤掉空串，因为空串是假值）
    """
    # ↓↓↓ 在这里写你的代码 ↓↓↓
    # 第 1 步：用正则找出所有词（findall 返回列表）
    所有词 = 词模式.findall(文本)

    # 第 2 步：把空串滤掉（空串是假值，if 判 False 就被跳过）
    结果 = []
    for w in 所有词:
        if w:
            结果.append(w)
    return 结果

    # ↑↑↑ 在这里写你的代码 ↑↑↑


# =============================================================================
# 【核心 2】统计词频
# =============================================================================
def 统计词频(词们):
    """统计每个词出现了多少次，返回 {词: 次数} 字典。

    ⬅ TODO 2（你来写）：两行左右

    要求：
      ① 建一个空字典
      ② 遍历词们，每个词的计数 +1

    用到的 API：
      d[w] = d.get(w, 0) + 1     ← 这行你写过很多次了

    ⚠️ 变量名别撞：字典叫「计数」，循环变量叫「词」——
       你在 E02 栽过（累加器叫 t 撞上字典 t → AttributeError）。
    """
    # ↓↓↓ 在这里写你的代码 ↓↓↓
    计数 = {}
    for 词 in 词们:
        计数[词] = 计数.get(词, 0) + 1  # 这行你写过很多次了
    return 计数

    # ↑↑↑ 在这里写你的代码 ↑↑↑


# =============================================================================
# 【核心 3】取前 N 个
# =============================================================================
def 取前N(计数, N):
    """返回出现次数最多的 N 个词，按「次数降序 + 词升序」排。

    ⬅ TODO 3（你来写）：一行

    要求：
      ① 用 sorted 把 计数.items() 排序
      ② key 要保证【同样的输入永远得到同样的顺序】
         —— 见 Q3。提示：key 可以返回一个【元组】，比如 (-次数, 词)
      ③ 降序还是升序？想清楚负号放在哪
      ④ 最后切前 N 个（[:N]）

    用到的 API：
      计数.items()              → [(词, 次数), (词, 次数), ...]
      sorted(..., key=...)      → 按你指定的 key 排序
      [ :N ]                    → 列表切片，取前 N 个
    """
    # ↓↓↓ 在这里写你的代码 ↓↓↓
    return sorted(计数.items(), key=lambda x: (-x[1], x[0]))[:N]
    # ↑↑↑ 在这里写你的代码 ↑↑↑


# =============================================================================
# 【输出】
# =============================================================================
def 显示结果(前N, 总词数, 不同词数):
    """把统计结果打印到终端。"""
    print("=" * 60)
    print(f"词频统计结果（总词数 {总词数}，不同词 {不同词数} 个）")
    print("=" * 60)
    if not 前N:
        print("  （没有统计到任何词）")
        return
    最多次数 = 前N[0][1]
    print(f"  {'排名':<6}{'词':<20}{'次数':<8}{'占比':<10}")
    print("  " + "-" * 56)
    for 名次, (词, 次数) in enumerate(前N, start=1):
        # 占比 = 这个词占全部词数的百分比
        占比 = 次数 / 总词数 * 100 if 总词数 else 0
        # 条形图：让高频词一眼能看出来
        条 = "█" * round(次数 / 最多次数 * 20)
        print(f"  {名次:<6}{词:<20}{次数:<8}{占比:>6.2f}%  {条}")
    print("=" * 60)


# =============================================================================
# 【命令行入口】
# =============================================================================
def main():
    """解析命令行参数 → 读文件 → 统计 → 打印。"""

    # ---- 1. 准备解析器 ----
    解析器 = argparse.ArgumentParser(
        description="统计文本文件里每个词出现了多少次（支持中英文混排）",
        epilog="示例：python 词频统计器.py 示例文本.txt --top 5",
    )
    解析器.add_argument(
        "文件",                       # 位置参数：必填，要统计哪个文件
        help="要统计的文本文件路径",
    )
    解析器.add_argument(
        "--top", type=int, default=10, # 可选参数：要显示前几名
        help="显示前 N 个词（默认 10）",
    )

    # ---- 2. 解析参数 ----
    参数 = 解析器.parse_args()

    # ---- 3. 检查文件在不在（这一步就是「友好提示」层）----
    路径 = Path(参数.文件)
    if not 路径.exists():
        print(f"❌ 找不到文件：{路径}")
        print(f"   当前目录里的 .txt 文件有：")
        for p in sorted(Path(".").glob("*.txt")):
            print(f"     - {p.name}")
        sys.exit(1)               # 退出码 1 = 出错了

    if not 路径.is_file():
        print(f"❌ 这不是一个文件：{路径}")
        sys.exit(1)

    # ---- 4. 读文件 ----
    # ⚠️ encoding="utf-8" 必须写 —— 不写的话 Windows 默认 GBK，
    #    读中文会报 UnicodeDecodeError（乱码/崩溃）
    try:
        文本 = 路径.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        print(f"❌ 这个文件不是 UTF-8 编码，中文可能读不了：{路径}")
        print("   建议：用记事本「另存为」→ 编码选「UTF-8」")
        sys.exit(1)

    # ---- 5. 统计 ----
    词们 = 切词(文本)
    计数 = 统计词频(词们)
    前N = 取前N(计数, 参数.top)

    # ---- 6. 打印 ----
    显示结果(前N, len(词们), len(计数))


if __name__ == "__main__":
    main()
