# 第 2 题 · 为什么 * 和 ** 在【定义处】和【调用处】含义不同？
# ============================================================
# 这题是今天【最核心】的一题。
# * 在两个位置是两回事：
#   · 定义处  *args  = 「把多出来的位置参数【打包】成元组」
#   · 调用处  *列表   = 「把列表【拆开】成一个个位置参数」
# ** 同理：
#   · 定义处  **kwargs = 「把多出来的关键字参数【打包】成字典」
#   · 调用处  **字典   = 「把字典【拆开】成一个个关键字参数」
#
# 你的任务：
#   ① 预测下面 4 行的输出
#   ② 跑一遍验证
#   ③ 解释：为什么 * 和 ** 在【定义处】和【调用处】含义不同？
#      用一句话总结：调用处的 * 和定义处的 * 分别是「打包」还是「拆包」？
# ---------------------------------------------------------------
print('2')
def g(*args, **kwargs):
    print("args =", args)
    print("kwargs =", kwargs)


数据 = [1, 2, 3]
选项 = {"x": 10, "y": 20}

# 下面两行的输出，动手跑一遍看：
g(*数据, **选项)
g(数据, 选项)       #   ← 注意：不加星号会怎样？

# 我的预测：
# ① g(*数据, **选项)：（1，2，3，{'x': 10, 'y': 20}）
# ② g(数据, 选项)：[1,2,3],{"x": 10, "y": 20}
#
# 实际输出：
#args = (1, 2, 3)
#kwargs = {'x': 10, 'y': 20}
#args = ([1, 2, 3], {'x': 10, 'y': 20})
# ✅ ③ 答案（读一遍，能合上文件复述出来就是真懂了）：
#    定义处的 * ：【打包】——把调用时多出来的位置参数收进一个元组 args
#    调用处的 * ：【拆包】——把列表/元组拆开，一个个递进去
#    ** 同理：定义处把多出来的关键字参数【打包】成字典，调用处把字典【拆开】逐个传。
#    一句话：同一个符号，看它站在哪——站在 def 里是口袋，站在调用里是手。
#    ⚠️ 顺带修你预测①的小偏差：args 和 kwargs 是【两个分开的口袋】——
#       g(*数据, **选项) 的结果是 args=(1,2,3)、kwargs={'x':10,'y':20}，
#       字典不会混进元组里。


