    print()
    print("=" * 60)
    print("【第 2 组】边界 / 无解用例")
    print("=" * 60)
    for numbers, target, 说明 in 边界用例:
        try:
            实际_慢 = two_sum_slow(numbers, target)
            实际_快 = two_sum_sorted(numbers, target)
        except Exception as e:
            print(f"❌ {说明}")
            print(f"   跑挂了：{type(e).__name__}: {e}")
            失败 += 1
            continue

