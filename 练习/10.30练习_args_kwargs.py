#    ② my_sum() 不传参 → args 是空元组 ()，循环一次都不跑，counts 保持 0 → 返回 0，不报错。
#    ③ 为什么必须 *args：
#       · 普通参数（比如 def my_sum(a, b)）：个数写死，传 0 个直接报
#         missing 2 required positional arguments——「任意多个」根本做不到；
#       · 用 *列表：调用方得先造好列表再拆包 my_sum(*[1, 2, 3])，多一步、别扭；
#       · *args = 调用方想传几个传几个，函数这边自动打包收下——这才叫"任意多个"。


