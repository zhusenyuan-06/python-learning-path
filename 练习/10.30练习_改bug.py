def 求和_错版(nums):
    """❌ 有 bug 的版本。"""
    nums = 0           # ← 把传进来的列表覆盖成了数字 0
    for i in nums:     # ← 这里的 nums 已经是 0 了，for 会直接报错
        nums += i
    return nums


