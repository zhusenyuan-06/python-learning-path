# 【错误分析】（11-10 实跑复现，不是口算）
#
# 错误 1：`if ch <= -1` —— 判断错了对象（落笔落错层）
#     实跑输出：
#         ch = "a"
#         ch <= -1  →  TypeError: '<=' not supported between instances of 'str' and 'int'
#     原因：ch 是【字符】（str），要判断的【计数】在 d[ch] 里（int）。
#           脑子里想的是「计数变负了」，手下写的是「字符变负了」——
#           概念抓对了，但落笔落到了另一层。
#     修法：if d[ch] < 0:  return False
#           （用 < 0 而不是 <= -1：语义直白「负数」，读代码的人不用想）
#
# 错误 2：`if d.values()` —— 静默错误（能跑，但结果全错）
#     实跑输出：
#         d = {'a': 0, 'b': 3}     ← 明显不相等
#         bool(d.values()) → True  ← 却判定成真
#     原因：d.values() 返回的【不是列表，是视图对象】。
#           视图对象只要字典非空就【永远为真】。
#           如果补上冒号让它能跑，这个函数会【永远返回 True】，一个错都不报。
#           LeetCode 上 "rat" vs "car" 会直接 WA。
#     ⚠️ d.keys() 同理，也是永远为真的视图。
#        想要真正的列表得 list(d.values()) 或 list(d.items())。
#     修法：return all(v == 0 for v in d.values())
#           all(...) = 「所有元素都满足条件才算 True」；
#           any(...) = 「至少有一个满足就算 True」。
#
