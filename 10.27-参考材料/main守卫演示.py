# main守卫演示.py
# 演示 __name__ 的两种取值

print(f"[{__name__}] 文件开始执行")


def 我是工具函数():
    return "我是一个可以被别人 import 使用的函数"


# ===== 关键：下面这段只在「直接运行本文件」时执行 =====
if __name__ == "__main__":
    print(f"[{__name__}] ↓↓↓ 这段是测试代码 ↓↓↓")
    print("测试 1:", 我是工具函数())
    print("测试 2: 这个文件被直接运行了")
    print(f"[{__name__}] ↑↑↑ 测试代码结束 ↑↑↑")
