# ============================================================
# 【第 4 站】⭐ 标准库：不用装，直接能用
# ============================================================
#
# Python 自带一大堆现成的模块（标准库），直接 import 就能用：
#
#   import os        # 操作系统相关（路径、环境变量）
#   import sys        # Python 运行时相关
#   import json       # JSON 解析 ← 你后面做 LLM API 会天天用
#   import datetime   # 日期时间
#   import csv        # CSV 文件读写
#   import random     # 随机数
#   import os.path    # 路径拼接（跨平台）
#
# 三大模块类型：
#   1. 标准库    → 自带，直接用        import json
#   2. 第三方库  → pip install 装的     import pandas / requests
#   3. 自定义模块 → 自己写的 .py 文件    import 配送工具
#
# ⭐ 怎么知道标准库有什么？
#   Python 官方文档：https://docs.python.org/3/library/
