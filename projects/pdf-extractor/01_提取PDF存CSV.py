# ★TODO 1 —— 提取所有非空行
# ═════════════════════════════════════════════════════════════════════
def 提取所有行(pdf路径):
    """返回这个 PDF 里所有【非空行】的列表，每个元素是 (页码, 行文字)。

    页码从 1 开始（人看的页码），不是代码里的 0 开始。
    空行要丢掉（PDF 里每页开头有换行，留着会干扰判断）。

    返回示例：[ (1, '第1 页，共8 页'), (1, '1、当某个分组...'), ... ]

    💡 提示：
        doc = pymupdf.open(pdf路径)
        for 序号 in range(doc.page_count):
            文字 = doc[序号].get_text()
            for 一行 in 文字.split(chr(10)):     # 按换行拆成一行行
                ...
        doc.close()

    ⚠️ 两个细节：
        · 页码要 +1（doc[0] 是第 1 页，但存进去要写 1）
        · 空行要丢（PDF 每页开头有换行，留着会打断后面的题号判断）
    """
    doc = pymupdf.open(pdf路径)  # 打开 PDF，拿到一个文档对象

    所有行 = []  # 准备一个空篮子，专门装 (页码, 行文字) 这种二元组

    for 序号 in range(doc.page_count):  # 序号是 0 开始的：0=第1页, 1=第2页...
        文字 = doc[序号].get_text()  # 把这一页的文字全抠出来，是一个大字符串

        # 大字符串里还夹着换行，按 \n 拆成一行一行
        for 一行 in 文字.split("\n"):
            裸 = 一行.strip()  # 去掉首尾空白（PDF 排版留下的空格、换行残留）
            if 裸:  # 只留有内容的行，空行直接跳过
                # 关键：序号 + 1 才是人看的页码。doc[0] 是第 1 页，
                # 但它前面有 "第2 页，共8 页" 这种页眉，不 +1 会全部错位
                所有行.append((序号 + 1, 裸))

    doc.close()  # 用完关掉，释放文件句柄（不关在 Windows 上会锁住文件）

    return 所有行


# ═════════════════════════════════════════════════════════════════════
# ★TODO 2 —— 判断一行是不是「题目开头」
# ═════════════════════════════════════════════════════════════════════
def 是题目开头(行):
    r"""返回 True/False：这行是不是一道新题的开头。

    （开头那个 r 是"原始字符串"标记——docstring 里有 \d \s 这类正则，
      不加 r 的话 Python 3 会警告 invalid escape sequence）

    真实数据长这样（自己跑一遍看）：
        1、当某个分组在输出链路发送时，...      ← 是
        2、（）结构不是局域网拓扑结构。          ← 是
        10、电子邮件协议SMTP、...               ← 是
        A、处理时延                              ← 不是（这是选项）
        第1 页，共8 页                          ← 不是
        答：（1）因为生成多项式...               ← 不是

    ⚠️⚠️ 这里有三道【闸门】，少一道就会误判 —— 我第一版就栽在这：

    闸门1 · 题号只能 1~2 位数字
        排除「141」「202」「255」「230」这类。
        真实 PDF 里有这么几行，它们【不是题号】：
            已知IP 地址是141.14.75.24        ← 141 是 IP 的一段
            192.12.101.212                   ← 192 是 IP 的一段
            202、255                          ← 子网掩码的字节数

    闸门2 · 数字后面必须【紧跟】「、」或「.」，且「.」后面不能再跟数字
        排除「2.2*108m/s」这种小数 —— 它是「2.」+「2」，不是题号。
        真实 PDF 里有这么一行：
            2.2*108m/s 的速度在介质中传播

    闸门3 · 题号必须【紧贴】行首（前面不能有别的字）
        排除「…网络地址为_ _141.14.64.0」这种夹在句中的。

    💡 提示：正则可以写成一条：
           r"^\d{1,2}\s*[、]|^[0-9]{1,2}\.(?!\d)"
       —— 拆开讲就是：数字+顿号，或 数字+句点（且句点后不是数字）
    """
    s = 行.strip()  # 先去掉首尾空白，让正则从干净的字符开始匹配

    # ── 闸门 1 + 闸门 2 的「、」分支 ──
    #   \d{1,2}  → 题号只能是 1~2 位数字（挡住 141 / 202 / 255 这类 IP 片段）
    #   \s*      → 允许题号和顿号之间有空格（真实数据里就有 "9 、TCP..." 这种）
    #   [、]     → 题号后面必须紧跟中文顿号
    if re.match(r"^\d{1,2}\s*[、]", s):
        return True

    # ── 闸门 1 + 闸门 2 的「.」分支 ──
    #   [0-9]{1,2}\. → 1~2 位数字 + 英文句点
    #   (?!\d)      → 【负向预查】句点后面不能立刻跟数字
    #                 这一句专门挡小数： "2.2*108m/s" 是「2.」+「2」，
    #                 句点后跟了数字 → 不算题号
    #                 而 "2.（）结构..." 句点后是汉字 → 是题号
    return re.match(r"^[0-9]{1,2}\.(?!\d)", s) is not None


# ═════════════════════════════════════════════════════════════════════
# ★TODO 3 —— 判断一行是不是「选项开头」
# ═════════════════════════════════════════════════════════════════════
def 是选项开头(行):
    r"""返回 True/False：这行是不是某个选项的开头。

    （开头那个 r 是"原始字符串"标记——这个 docstring 里没有正则，
      但保持一致好习惯）

    真实数据长这样：
        A、处理时延        ← 是
        B、排队时延        ← 是
        C、传输时延        ← 是
        D、传播时延        ← 是
        A．最大传输速率     ← 是（全角句点也算）
        1、当某个分组...   ← 不是

    💡 提示：选项字母是 A/B/C/D，后面跟「、」或「.」（半角或全角）
    """
    # 字母 A~D（半角 + 全角 Ａ～Ｄ 都收），后面跟「、」或「.」「．」
    # 「.」是半角句点 U+002E，「．」是全角句点 U+FF0E——真实 PDF 里两种都出现过
    return re.match(r"^[A-DＡ-Ｄ]\s*[、.．]", 行.strip()) is not None


# ═════════════════════════════════════════════════════════════════════
# 补充处理 —— 一行里有多个选项怎么办
# ═════════════════════════════════════════════════════════════════════
def 拆开多选项(行):
    """如果一行里塞了好几个选项，返回拆开的列表；只有一个就返回原样。

    为什么需要这个？真实 PDF 里有两种"挤在一行"的情况：

        ① p1 原文： 'B、一对多通信C、面向报文'
           → B 和 C 挤在同一行。如果不拆，选项 C 就被吞进 B 里了

        ② p2 原文： 'A．最大传输速率　　B．最长帧长　　C．最短帧长　　D．最大站点数'
           → 4 个选项挤在一行，中间用全角空格（U+2003）分隔

    做法：把所有"选项字母 + 分隔符"的位置找出来，按这些位置切开。
          切出来的每一段都是完整的一个选项（保留它自己的 "A、" 前缀）。

    返回：["A、xxx", "B、yyy", ...]  至少有一个元素
    """
    # 找出这一行里所有选项标记的起始位置
    位置 = [m.start() for m in re.finditer(r"[A-DＡ-Ｄ]\s*[、.．]", 行)]

    # 只有 0 个或 1 个标记 → 不用拆，原样返回
    if len(位置) <= 1:
        return [行]

    结果 = []
    for i, 起 in enumerate(位置):
        # 这一段的终点 = 下一个标记的起点；最后一段一直切到行尾
        止 = 位置[i + 1] if i + 1 < len(位置) else len(行)
        结果.append(行[起:止].strip())  # 切出来再 strip，去掉分段边界上的空格

    return 结果


def 是页眉(行):
    """判断这行是不是 PDF 每页顶部的页眉（如 '第1 页，共8 页'）。

    页眉不是题目内容。不拦掉的话，它会被当成"题干续行"接进上一道题，
    污染数据（实测题 9 的题干末尾就混进了 '第2 页，共8'）。
    """
    return bool(re.match(r"^第\s*\d+\s*页", 行.strip()))


# ═════════════════════════════════════════════════════════════════════
# 以下是【已经写好的部分】，你填完上面 3 个 TODO 就能直接跑
# ═════════════════════════════════════════════════════════════════════

def 拆成题目(所有行):
    """把行列表拆成一道道题。

    返回：列表，每个元素是一个字典：
        {"题号": "1", "题干": "当某个分组在输出链路发送时，...",
         "选项": ["A、处理时延", "B、排队时延", "C、传输时延", "D、传播时延"]}

    规则：
      · 遇到「题目开头」→ 开一道新题
      · 遇到「选项开头」→ 挂到当前题的选项里
      · 其他行 → 如果当前有题，就当作题干的续行，接在题干后面
      · 遇到「选择题答案：」这一行 → 停，后面是答案表，不处理了
      · 遇到「填空题：」→ 选择题区结束，后面不处理（v1 只做选择题）
    """
    题目列表 = []
    当前题 = None
    已进别的区 = False

    for 页码, 行 in 所有行:
        裸 = 行.strip()
        if not 裸:
            continue

        # 到了答案表就停
        if 裸.startswith(答案表起点):
            break

        # 碰到「填空题：」这类分界标记 → 之后的内容不是选择题了
        # （选择题区到此为止，后面的填空题有自己的一套编号，会撞车）
        if 裸.startswith(分界标记):
            已进别的区 = True
            当前题 = None
            continue
        if 已进别的区:
            continue

        if 是题目开头(裸):
            # 新题开始
            题号 = re.match(r"^(\d+)", 裸).group(1)
            当前题 = {"题号": 题号, "题干": 裸, "选项": []}
            题目列表.append(当前题)
        elif 是选项开头(裸):
            if 当前题 is not None:
                # 这一行可能塞着多个选项（见 拆开多选项 的说明），
                # 所以不能只 append 一条，要把拆开的结果全都挂上
                当前题["选项"].extend(拆开多选项(裸))
        elif 是页眉(裸):
            # 页眉直接丢掉，绝不能接进题干
            continue
        else:
            # 续行归属：题干续 还是 选项续？看这道题【有没有出现过选项】
            #   · 还没出现选项 → 一定是题干被换行了（接题干）
            #   · 已经出现选项 → 是最后一个选项被换行了（接最后一个选项）
            # 实测题 7 的选项 C 被排版拆成两行：
            #   'C、具有多个IP 地址，...相同的网络号，并'
            #   '且占用一个主机号'      ← 这行是 C 的续行，不是题干！
            if 当前题 is None:
                continue
            if 当前题["选项"]:
                当前题["选项"][-1] += 裸  # 接在最后一个选项后面
            else:
                当前题["题干"] += 裸  # 接在题干后面

    return 题目列表


def 写成CSV(题目列表, csv路径):
    """把题目列表写成 CSV。返回写进去的行数（不含表头）。"""
    with open(csv路径, "w", newline="", encoding="utf-8-sig") as f:
        写手 = csv.writer(f)
        写手.writerow(["题号", "题型", "题干", "选项A", "选项B", "选项C", "选项D"])

        for 题 in 题目列表:
            选项 = 题["选项"]
            # 选项不足 4 个时，后面补空字符串，保证每行都是 7 列
            选项列 = [选项[i] if i < len(选项) else "" for i in range(4)]
            写手.writerow([题["题号"], "选择"] + [题["题干"]] + 选项列)

    return len(题目列表)


def 回读校验(csv路径):
    """读回 CSV 校验：返回 (行数, 表头列表)。"""
    with open(csv路径, "r", newline="", encoding="utf-8-sig") as f:
        读手 = csv.reader(f)
        表头 = next(读手)
        行数 = sum(1 for _ in 读手)
    return 行数, 表头


def main():
    print("=" * 60)
    print("📄 课件 PDF → 题库 CSV")
    print("=" * 60)

    # 素材存在吗？不存在就直接报错，别让脚本跑到一半才崩
    assert 素材PDF.exists(), f"素材 PDF 不存在：{素材PDF}"

    print("① 提取所有行…")
    所有行 = 提取所有行(素材PDF)
    print(f"   共 {len(所有行)} 个非空行")

    print("② 拆成题目…")
    题目列表 = 拆成题目(所有行)
    print(f"   共解析出 {len(题目列表)} 道题")

    print("③ 写 CSV…")
    输出目录.mkdir(exist_ok=True)
    行数 = 写成CSV(题目列表, 输出CSV)
    print(f"   已写入 {行数} 行 → {输出CSV}")

    print("④ 回读校验…")
    读回行数, 表头 = 回读校验(输出CSV)
    print(f"   回读 {读回行数} 行，表头 = {表头}")
    assert 读回行数 == 行数, "回读行数对不上！"
    assert 表头 == ["题号", "题型", "题干", "选项A", "选项B", "选项C", "选项D"], "表头不对！"

    print()
    print("=" * 60)
    print(f"🎉 完成：{行数} 道题已存进 {输出CSV.name}")
    print("=" * 60)

    # 前 3 道题打印出来给你眼看
    print("\n📋 前 3 道题（看看拆得对不对）：\n")
    for 题 in 题目列表[:3]:
        print(f"【第 {题['题号']} 题】{题['题干'][:60]}")
        for 选项 in 题["选项"]:
            print(f"    {选项}")
        print()


if __name__ == "__main__":
    main()
