"""
通讯录 Web 界面（Streamlit）—— 增删改查全部实现

【Streamlit 最大的坑】每次交互（点按钮/输入框变化）都会把整个脚本从上到下重跑一遍。
所以：
  1. 数据不能放全局变量（每次重跑会被重置）—— 用 st.session_state
  2. 不能一 import 就跑一堆副作用 —— 这就是 contact_book.py 要重构的原因

【状态】5 处 TODO 已由助手代填并讲透；仍需本人脱稿讲清 session_state 才能销账。
"""

import streamlit as st
from contact_book import 初始通讯录, 查询, 添加, 删除, 统计未填邮箱

# -------------------------------------------------------------------
# 1. 页面标题
# -------------------------------------------------------------------
st.set_page_config(page_title="我的通讯录", page_icon="📒")
st.title("📒 通讯录（Web 版）")
st.caption("数据只存在当前会话里，刷新页面会重置")

# st.rerun() 会清掉当次运行的所有输出，所以删除提示要先存进 session_state
if "提示" in st.session_state:
    提示 = st.session_state.提示
    if "已删除" in 提示:
        st.success(提示)
    else:
        st.warning(提示)
    del st.session_state.提示

# -------------------------------------------------------------------
# 2. 初始化 session_state（只在第一次运行时执行）
# -------------------------------------------------------------------
if "通讯录" not in st.session_state:
    st.session_state.通讯录 = dict(初始通讯录)   # 拷贝，别改原始数据

通讯录 = st.session_state.通讯录   # 拿到同一个 dict 的引用，改它=改 session_state

# -------------------------------------------------------------------
# 3. 添加联系人
# -------------------------------------------------------------------
st.subheader("➕ 添加联系人")
col1, col2 = st.columns(2)
姓名 = col1.text_input("姓名")
电话 = col2.text_input("电话")
地址 = col1.text_input("地址")
邮箱 = col2.text_input("邮箱（可不填）")

if st.button("添加"):
    # TODO A：空姓名拦截 + 调 添加() + 按返回值给绿/黄提示
    if not 姓名.strip():
        st.warning("姓名不能为空")
    else:
        结果 = 添加(通讯录, 姓名, 电话, 地址, 邮箱)
        if "已添加" in 结果:
            st.success(结果)
        else:
            st.warning(结果)

# -------------------------------------------------------------------
# 4. 删除联系人
# -------------------------------------------------------------------
st.subheader("🗑️ 删除联系人")
删谁 = st.selectbox("选一个人", options=list(通讯录.keys()) or ["（暂无联系人）"])

if st.button("删除"):
    # TODO B：调 删除() → 提示存 session_state → st.rerun() 刷新下拉框
    if 删谁 == "（暂无联系人）":
        st.warning("通讯录为空，没有可删除的人")
    else:
        结果 = 删除(通讯录, 删谁)
        st.session_state.提示 = 结果
        st.rerun()

# -------------------------------------------------------------------
# 5. 查询
# -------------------------------------------------------------------
st.subheader("🔍 查询")
查谁 = st.text_input("姓名")
查字段 = st.selectbox("字段", ["电话", "地址", "邮箱"])
if st.button("查询"):
    # TODO C：调 查询() + st.write 显示
    结果 = 查询(通讯录, 查谁, 查字段)
    st.write(f"**{查谁}** 的{查字段}：{结果}")

# -------------------------------------------------------------------
# 6. 全部联系人 + 统计
# -------------------------------------------------------------------
st.subheader("📋 全部联系人")
行 = [
    {
        "姓名": 人,
        "电话": 资料.get("电话", ""),
        "地址": 资料.get("地址", ""),
        "邮箱": 资料.get("邮箱", ""),
    }
    for 人, 资料 in 通讯录.items()
]
st.dataframe(行, use_container_width=True)

名单, 人数 = 统计未填邮箱(通讯录)
st.caption(f"没填邮箱的：{名单}（共 {人数} 人）")
