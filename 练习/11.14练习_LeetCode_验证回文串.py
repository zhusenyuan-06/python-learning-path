import re

# LeetCode 官方会传进来的函数签名
class Solution:
    def isPalindrome(self, s: str) -> bool:
        # ---------- 解法一：正则清洗法（3 行搞定）----------
        # 第 1 步：把【所有非字母数字字符】删掉
        #   [^a-zA-Z0-9] 的意思是「不在 a-z、A-Z、0-9 里面的任意一个字符」
        #   [] 里面开头写 ^ 是【取反】，跟正则开头的 ^（行首）不是一个意思
        清洗后 = re.sub(r"[^a-zA-Z0-9]", "", s)      # sub(模式, 替换成什么, 原串)
        #   ⚠️ 第二个参数是 ""（空串）= 把匹配到的字符【删掉】，不是删成空
        #
        # 第 2 步：统一转小写（题目规定「忽略大小写」）
        清洗后 = 清洗后.lower()                        # .lower() 返回新字符串，原串不变
        #
        # 第 3 步：和【自己反转后】比较，相等就是回文
        return 清洗后 == 清洗后[::-1]                   # [::-1] 是切片反转（步长为 -1）
        #   ⚠️ 切片 s[::-1] 和 s.reverse() 不一样：
        #      切片 = 产生【新字符串】，原串不变，可以直接拿去比较
        #      reverse() = 【原地】改原串，返回 None，拿它比较会报 TypeError


# =============================================================================
# 解法二：双指针（不靠正则，纯 Python 逻辑）
#
#   两个指针 left / right 从两头往中间走：
#     - 如果左边的字符不是字母数字 → left 右移跳过它
#     - 如果右边的字符不是字母数字 → right 左移跳过它
#     - 否则比较两个字符（先都转小写）：
#         不一样 → 直接返回 False
#         一样   → 两个指针都往中间走一步
#   left >= right 时说明检查完了 → 返回 True
#
#   💡 提示 1：判断「是不是字母或数字」不用正则也行 ——
#             Python 内置的 s.isalnum() 就是干这个的（字母或数字返回 True）。
#   💡 提示 2：⚠️ 你的错题池里有 E15「缺 reverse / 缺 else」这一族，
#             这里【必须写 else 分支】——指针要往中间走，
#             漏了 else 就会死循环。
#   💡 提示 3：⚠️ 还有一个坑 —— 用 s.lower() 比较可以，
#             但不要用 s.lower() == s.upper() 这种偷懒法（面试不认）。
# =============================================================================
def is_palindrome_two_pointer(s: str) -> bool:
    # 两个指针分别站在字符串的最左和最右
    left = 0                    # 左指针：起点
    right = len(s) - 1          # 右指针：终点（len-1，因为下标从 0 开始）

    # while 而不是 if：可能要跳好几个符号才能比较，所以是循环
    while left < right:         # 两个指针还没交错 → 还要继续比
        # ---------- 左边跳过非字母数字 ----------
        # ⚠️ 内层 while 必须带 left < right 的条件！
        #    否则像 ".," 这种全是符号的串，左指针会一路冲过 right 变成负数下标 → IndexError
        while left < right and not s[left].isalnum():
            left += 1            # 跳过这个符号，指针右移一格

        # ---------- 右边跳过非字母数字 ----------
        # 同理也要带 left < right，否则会越界
        while left < right and not s[right].isalnum():
            right -= 1           # 跳过这个符号，指针左移一格

        # ---------- 真正比较 ----------
        # 两边都是字母数字了，转小写后比
        if s[left].lower() != s[right].lower():
            return False         # 不等 → 立刻判定【不是】回文，直接返回
        # ⚠️ 这里【必须有 else 分支】把指针往中间走！
        #    如果比较相等却什么都不做 → while 永远成立 → 【死循环】（E15 那一族）
        else:
            left += 1            # 相等 → 左指针右移
            right -= 1           # 相等 → 右指针左移

    # left >= right：说明所有能比的都比完了，没有发现不等 → 是回文
    # ⚠️ 注意这里【没有再比较一次中间那个字符】
    #    奇数长度串的中间字符跟自己比必然相等，比了也是白比
    return True


# =============================================================================
# 加分项：能不能用【一条正则】直接判断是不是回文？
#
#   ⚠️ 我第一版写的是 re.search(r"^(.+)(?=\1$)", s) —— 实测【不工作】，返回 None。
#      为什么：贪婪的 (.+) 把整串吃光后，位置上已经没有内容留给 \1；
#      回溯时 \1 又是「两字符长」，跟奇数长度的串对不上。
#
#   ✅ 能用的写法（已实跑验证）：
#        re.match(r"^(.)(?=.*\1$)|^.$", s)
#      拆开看：
#        ^(.)        先把【第一个字符】固定下来（捕获成组 1）
#        (?=.*\1$)   断言：在后面某处能再找到一个【相同的字符】，且它正好在结尾
#                    (?=...) 叫【预查/断言】—— 只判断位置，不消费字符
#        |^.$        单字符特判（"a" 也要算回文，但上面那条匹配不到）
#
#   实跑结果：
#      'aba'  -> True      'abcd' -> False     'a'   -> True
#      'aa'   -> True      'abba' -> True      'ab'  -> False
#
#   ⚠️ 注意：这条只对【已经清洗过】的纯字母数字串有效，
#      而且不区分大小写 —— 用之前要先 .lower()。
# =============================================================================
def is_palindrome_one_regex(s: str) -> bool:
    """⚠️ 这【不是】回文判定！只判【首尾字符是否相同】。留着当反面教材。"""
    清洗后 = re.sub(r"[^a-zA-Z0-9]", "", s).lower()   # 先清洗 + 转小写
    if 清洗后 == "":                                  # 全是符号的情况
        return True                                  # 清空后是回文
    # 匹配成功返回 Match 对象（真值），失败返回 None（假值）→ 直接当布尔用
    return bool(re.match(r"^(.)(?=.*\1$)|^.$", 清洗后))


