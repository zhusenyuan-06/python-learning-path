print("===== 第 3 段：*菜单 和 **附加 到底是什么类型 =====")


def 看类型(园所名, *菜单, **附加):
    print("      园所名 =", repr(园所名), "->", type(园所名).__name__)
    print("      菜单   =", repr(菜单), "->", type(菜单).__name__)
    print("      附加   =", repr(附加), "->", type(附加).__name__)


看类型("云湖湾", "青菜", "豆腐", 供应商="锦源", 日期="2026-09-15")
print("  注意：菜单是【元组】不是列表，附加是【字典】")


