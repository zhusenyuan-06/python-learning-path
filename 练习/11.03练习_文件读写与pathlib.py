# 任务 3：用 pathlib 处理 练习/ 目录
#   ① 统计 练习/ 下有多少个 .py 文件
#   ② 找出文件名含「练习」的 .py 文件，打印文件名 + 文件大小
#   ③ 把清单写进 练习/输出/文件清单.txt（路径用 pathlib 拼，别手拼字符串）
# ============================================================
from pathlib import Path
# from pathlib import Path = 从 pathlib 模块里导入 Path 类
# pathlib 是 Python 处理路径的"正规军"，比手拼字符串安全得多

p = Path(".")                         # 当前目录
# Path(".") = 把字符串 "." 变成一个【路径对象】（不是普通字符串了）
print(p.resolve())                    # 转成绝对路径
# .resolve() = 把相对路径转成完整的绝对路径，方便看清文件到底在哪
for f in p.glob("*练习*.py"):             # 找当前目录下所有 练习
    # .glob(通配符) = 按文件名模式找文件，返回一个【生成器】
    # 通配符 * 匹配任意字符，所以 "*练习*.py" = 文件名含「练习」且以 .py 结尾
    # ✅ 这个写法比"先遍历再 if 判断"更干脆，是好写法
    print(f.name)
    # f.name = 只取文件名部分

for f in p.glob("*练习*.py"):
    # 同一个 p 再 glob 一次是可以的（glob 每次都重新遍历目录）
    print(f.name, f.stat().st_size)
    # f.stat() = 查看文件状态信息；.st_size = 文件大小（字节）
    # 对比：os.path.getsize() 也能拿大小，但要传字符串路径，pathlib 直接 f.stat().st_size 更简洁

