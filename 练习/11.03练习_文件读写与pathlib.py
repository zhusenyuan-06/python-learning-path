# ============================================================
# 任务 2：读 练习/文本.txt
#   ① 打印整个文件内容 ② 打印总行数 ③ 打印第2行 ④ 逐行打印每行前5个字符
# ============================================================
with open("文本.txt", "r", encoding="utf-8") as f:
    # "r" = 读取模式（和 "w" 相对）。文件不存在会报 FileNotFoundError
    列表 = f.readlines()
    # f.readlines() 一次读【所有行】，返回【列表】，每个元素是一行（末尾带 \n）
    # 关键：读完之后文件的"指针"就停在末尾了，同一个 f 再读会读到空

print("".join(列表))     # ① 打印整个内容
# "".join(列表) = 用【空字符串】把列表里的多行拼回一个完整字符串
# 为什么用 "" 而不是 "\n"？因为每个元素末尾本来就带 \n，用 "\n" 会变成每行后面两个换行 → 全是空行
print(len(列表))      # ② 行数
# len(列表) = 列表里有多少个元素 = 文件有多少行
print(列表[1])        # ③ 第2行
# 列表[1] 取第 2 个元素。列表索引从 0 开始：列表[0]是第1行，列表[1]是第2行


with open("文本.txt", "r", encoding="utf-8") as f:
    # ⚠️ 必须【重新开一次门】！上一个 with 块结束时 f 已经被自动关闭了
    #    如果在同一个 with 块里先 read() 再 readlines()，第二次会读到空
    for line in f:  # → 一次只给你一行
        # for line in f = 逐行读文件，每轮循环拿到一行，这是处理大文件的标准姿势
        print(line[:5])
        # line[:5] = 切片，取这一行的前 5 个字符
        # ⚠️ 坑：行尾的 \n 也在字符串里，如果某行不足 5 个字符，切片会把 \n 也切进来，打印就错位
        #    稳妥写法：print(line.strip()[:5])  先去首尾空白再切
        #    本文件每行都够长，所以这次没暴露出来


