print("===== 第 4 段：拆包方向 —— 把容器拆开送进去 =====")


def 收(第一个, *其余, **选项):
    print("      第一个 =", 第一个, "| 其余 =", 其余, "| 选项 =", 选项)


菜单数据 = ["青菜", "豆腐", "排骨"]
附加数据 = {"供应商": "锦源", "日期": "2026-09-15"}
print("  不拆包，直接传列表：")
收("云湖湾", 菜单数据, 附加数据)
print("  用 * 拆列表、用 ** 拆字典：")
收("云湖湾", *菜单数据)
收("云湖湾", *菜单数据, **附加数据)
print("  ↑ 这两行等价于：")
print("      收(\"云湖湾\", \"青菜\", \"豆腐\", \"排骨\", 供应商=\"锦源\", 日期=\"2026-09-15\")")


print()
print("===== 第 5 段：你的汇总配送单（逐行拆）=====")


def 汇总配送单(园所名, *菜单, **附加):
    print("      园所:", 园所名)
    print("      菜单:", ", ".join(菜单))
    for 键, 值 in 附加.items():
        print("      " + 键 + ":", 值)


汇总配送单("云湖湾", "青菜", "豆腐", "排骨", 供应商="锦源", 日期="2026-09-15")
print("  拆解：")
print("      园所名 = '云湖湾'                    ← 固定 1 个，直接收")
print("      菜单   = ('青菜','豆腐','排骨')        ← 多余的位置参数，打包成元组")
print("      附加   = {'供应商':'锦源','日期':'...'} ← 多余的关键字参数，打包成字典")
print("      所以 \", \".join(菜单) 能用（join 接受元组）")
print("      所以 附加.items() 能用（字典自带 items）")


print()
print("===== 第 6 段：* 的真正杀手锏 —— 万能转发 =====")


def 我的打印(*内容, **选项):
    """把收到的原样转交给内置 print"""
    print(*内容, **选项)


我的打印("苹果", "香蕉", "橘子")
我的打印("苹果", "香蕉", "橘子", sep=" | ")
我的打印("苹果", "香蕉", end="")
print("   <- 上面 end 吃掉了换行")
print("  不写 *args / **kwargs，你根本写不出能接受任意参数的 print 包装器")


