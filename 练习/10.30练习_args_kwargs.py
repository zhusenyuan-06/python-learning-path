def my_sum(*args):
    """求所有数字的和。"""
    # ← 你的答案写在这里
    counts = 0  # 累加器另起名，不碰入参 nums
    for i in args:  # nums 还是原来那个列表
        counts += i
    return counts

# 测试（写完把下面的注释取消）：
