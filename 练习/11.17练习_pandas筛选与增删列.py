#
# ① 布尔索引筛选（最常用）
#     df[条件] → 条件为 True 的那些行
#     单个条件：df[df['星期'] == '星期二']
#
# ② 多个条件 = AND（同时满足）
#     必须【每个条件各自加括号】，用 & 连接，不能用 Python 的 and
#     df[(df['星期'] == '星期一') & (df['序号'] > 5)]
#     ⚠️ 写成 df[df['星期'] == '星期一' and df['序号'] > 5] 会报错
#
# ③ 多个条件 = OR（满足其一）
#     用 | 连接：df[(df['列A'] == 1) | (df['列B'] == 2)]
#
# ④ 按关键词找行（列里是长文本时）
#     df[df['新闻内容'].str.contains('银行')]
#     ⚠️ str.contains 默认按【正则】匹配！要找字面量就加 regex=False：
#        df[df['新闻内容'].str.contains('银行', regex=False)]
#        （因为 '银行.' 里的 . 会当成「任意一个字符」，多匹配出别的行）
#
# ⑤ 新增一列
#     df['新列名'] = 一列和 df 等长的数据
#     数值派生：df['双倍序号'] = df['序号'] * 2
#     字符串派生：df['标签'] = df['星期'] + '-' + df['序号'].astype(str)
#                ⚠️ 序号是数字，拼字符串前要先 .astype(str)，否则 TypeError
#
# ⑥ 删除列
#     df.drop(columns=['新闻内容'])
#     ⚠️ drop 默认【不改原表】，要真删得写 df = df.drop(columns=['新闻内容'])
#
# ⑦ 重命名列
#     df.rename(columns={'序号': '编号'})
#
# ⑧ 排序
#     df.sort_values(by='序号', ascending=False)   # False = 倒序
#
# ------------------------------------------------------------------
# ⚠️ 坑（照着踩一遍学费最省）
# ------------------------------------------------------------------
#
# 坑1 · 取一列 vs 取多列
#      df['星期']        → 一个 Series（一列）
#      df[['星期','序号']] → 一个 DataFrame（多列，方括号套方括号）
#      写成 df['星期','序号'] 会报 KeyError
#
# 坑2 · and / or 不能用在 pandas 条件上
#      pandas 条件必须用 & 和 |，且每个条件加括号
#
# 坑3 · str.contains 默认是正则，不是字面量匹配
#
# 坑4 · 先筛选、再改列 → pandas 会警告 SettingWithCopyWarning
#      筛选结果先 .copy() 再改，就不会警告、也不会改到原表
#
# 坑5 · 新增的列【必须和原表等长】
#      df['新列'] = 一个长度对不上的东西 → 报 ValueError
#
# 坑6 · 数字列和字符串列别混着比
#      '序号' 是 int64，跟 5 比；'星期' 是 object，跟 '星期二' 比
# ================================================================================


