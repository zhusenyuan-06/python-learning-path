print("===== 第 2 段：死板写法 vs 灵活写法 =====")


def 死板汇总(园所名, 菜单1, 菜单2, 菜单3):
    print("      ", 园所名, 菜单1, 菜单2, 菜单3)


def 灵活汇总(园所名, *菜单, **附加):
    print("      ", 园所名, "| 菜单 =", 菜单, "| 附加 =", 附加)


print("  死板版：刚好 3 个菜单")
死板汇总("云湖湾", "青菜", "豆腐", "排骨")

print("  死板版：只有 2 个菜单")
try:
    死板汇总("云湖湾", "青菜", "豆腐")
except TypeError as e:
    print("      报错 ->", e)

print("  死板版：来了 4 个菜单")
try:
    死板汇总("云湖湾", "青菜", "豆腐", "排骨", "牛肉")
except TypeError as e:
    print("      报错 ->", e)

print("  灵活版：3 个菜单 + 2 个附加")
灵活汇总("云湖湾", "青菜", "豆腐", "排骨", 供应商="锦源", 日期="2026-09-15")
print("  灵活版：1 个菜单，什么附加都没有")
灵活汇总("云湖湾", "青菜")
print("  灵活版：6 个菜单 + 3 个附加")
