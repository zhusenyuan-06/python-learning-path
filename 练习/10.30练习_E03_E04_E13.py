停用词 = {"的", "了", "是", "我", "你", "在", "the", "a", "an"}


def 词频统计(文本, n=3):
    """完整的词频统计器。
    要求：清洗链完整 + 排名从高到低 + 返回前 n 名。
    """
    # ← 你的答案写在这里
    # ❌ 原答案保留对照——四要素里三个对（赋值/字符集/停用词/reverse），但漏了【判空】：
    #    strip 后可能变空串（"..." 整个被剥光），空串 "" 不在停用词集合里
    #    → 被算进 counts，多出一个 '' 键（E19）。且判空必须排在停用词【前面】。
    #    return 后面那行 pass 是死代码，永远执行不到，已删。
    counts = {}
    for w in 文本.split():
        w = w.lower().strip(".,!?，。！？")   # ① E13赋值 + E03全字符集
        if not w:                             # ② E19判空（必须最先）
            continue
        if w in 停用词:                        # ③ 停用词
            continue
        counts[w] = counts.get(w, 0) + 1
    return sorted(counts.items(), key=lambda x: x[1], reverse=True)[:n]  # ④ E04降序


