# -*- coding: utf-8 -*-
"""01 · 课件 PDF → 题库 CSV（v1.1）

做什么：读一份 PDF 复习资料 → 认出哪些行是题干、哪些行是选项 → 存成 CSV 题库。

素材：《计算机网络基础》复习 题-答案版.pdf（8 页）
输出：输出/计算机网络基础_题库.csv
"""

import csv
import re
from pathlib import Path

import pymupdf

# ═════════════════════════════════════════════════════════════════════
# 路径配置
# ═════════════════════════════════════════════════════════════════════

项目目录 = Path(__file__).parent
输出目录 = 项目目录 / "输出"

# 素材在 Downloads 里。用 Path.home() 推导，不写死用户名（这仓库是公开的）
素材目录 = Path.home() / "Downloads"
素材PDF = 素材目录 / "《计算机网络基础》复习 题-答案版.pdf"

输出CSV = 输出目录 / "计算机网络基础_题库.csv"

# 碰到这些行说明进了别的题型区，不再当选择题处理
分界标记 = ("填空题：", "填空题:", "选择题答案", "填空题答案")

# 答案表从这里开始 —— 之前的行才是题目
答案表起点 = "选择题答案"


# ═════════════════════════════════════════════════════════════════════
# 1. 打开 PDF
# ═════════════════════════════════════════════════════════════════════
def 打开PDF(pdf路径):
    """打开 PDF，返回文档对象。失败就带着原因退出。

    返回：pymupdf 文档对象
    退出：SystemExit（素材不存在 / 文件损坏 / 有打开密码）
    """
    if not pdf路径.exists():
        raise SystemExit(
            f"❌ 素材 PDF 不存在：{pdf路径}\n"
            f"   把它放到这个路径，或改脚本顶部的 素材PDF 那一行。"
        )

    try:
        doc = pymupdf.open(pdf路径)
    except Exception as e:
        raise SystemExit(
            f"❌ PDF 打不开：{pdf路径}\n"
            f"   原因：{type(e).__name__}: {e}\n"
            f"   多半是文件损坏、不是 PDF、或者有打开密码。"
        ) from e

    # 有密码的 PDF 打开时不报错，但内容读不出来，必须专门查一次
    if doc.needs_pass:
        doc.close()
        raise SystemExit(f"❌ PDF 有打开密码，先解密再跑：{pdf路径}")

    return doc


# ═════════════════════════════════════════════════════════════════════
# 2. 提取所有非空行
# ═════════════════════════════════════════════════════════════════════
def 提取所有行(pdf路径):
    """把 PDF 里所有非空行读出来。

    返回：[(页码, 行文字), ...]，页码从 1 开始（人看的页码）
    """
    doc = 打开PDF(pdf路径)
    所有行 = []

    try:
        for 序号 in range(doc.page_count):
            try:
                文字 = doc[序号].get_text()
            except Exception as e:
                # 某页取字失败就跳过这一页，别让整篇报废
                print(f"   ⚠️ 第 {序号 + 1} 页取文字失败，跳过：{e}")
                continue

            for 一行 in 文字.split("\n"):
                裸 = 一行.strip()
                if 裸:
                    # 序号 + 1 才是人看的页码，doc[0] 是第 1 页
                    所有行.append((序号 + 1, 裸))
    finally:
        # 放 finally 里：中途抛异常也保证关闭
        # 写在 for 后面那一行的话，异常一抛就跳过了，Windows 上文件会被锁住
        doc.close()

    if not 所有行:
        raise SystemExit(
            "❌ 一行文字都没提到。多半是扫描版 PDF（只有图、没文字层），得先 OCR。"
        )

    return 所有行


# ═════════════════════════════════════════════════════════════════════
# 3. 判断一行是不是题目开头
# ═════════════════════════════════════════════════════════════════════
def 是题目开头(行):
    """这行是不是一道新题的开头。返回 True/False。

    三道闸门，缺一道就会误判：
      1. 题号只能 1~2 位数字（挡住 IP 里的 141、掩码里的 255）
      2. 数字后必须跟「、」或「.」，且「.」后不能跟数字（挡住小数 2.2）
      3. 题号必须紧贴行首（挡住句子中间冒出来的数字）
    """
    s = 行.strip()

    # 闸门 1 + 2 的「、」分支：数字 + 中文顿号
    if re.match(r"^\d{1,2}\s*[、]", s):
        return True

    # 闸门 1 + 2 的「.」分支：1~2 位数字 + 句点，且句点后不是数字
    return re.match(r"^[0-9]{1,2}\.(?!\d)", s) is not None


# ═════════════════════════════════════════════════════════════════════
# 4. 判断一行是不是选项开头
# ═════════════════════════════════════════════════════════════════════
def 是选项开头(行):
    """这行是不是某个选项的开头（A/B/C/D + 分隔符）。返回 True/False。"""
    # 分隔符有三种：中文顿号「、」、半角句点「.」、全角句点「．」
    return re.match(r"^[A-DＡ-Ｄ]\s*[、.．]", 行.strip()) is not None


# ═════════════════════════════════════════════════════════════════════
# 5. 一行里塞了多个选项时拆开
# ═════════════════════════════════════════════════════════════════════
def 拆开多选项(行):
    """一行里有多个选项就拆开；只有一个就原样返回。

    真实数据有两种挤法：
      B、一对多通信C、面向报文
      A．最大传输速率　　B．最长帧长　　C．最短帧长
    """
    位置 = [m.start() for m in re.finditer(r"[A-DＡ-Ｄ]\s*[、.．]", 行)]

    if len(位置) <= 1:
        return [行]

    结果 = []
    for i, 起 in enumerate(位置):
        止 = 位置[i + 1] if i + 1 < len(位置) else len(行)
        结果.append(行[起:止].strip())

    return 结果


# ═════════════════════════════════════════════════════════════════════
# 6. 判断是不是 PDF 页眉
# ═════════════════════════════════════════════════════════════════════
def 是页眉(行):
    """是不是每页顶部的页眉（如「第1 页，共8 页」）。返回 True/False。

    不拦掉的话，它会被当成题干续行接进上一道题。
    """
    return bool(re.match(r"^第\s*\d+\s*页", 行.strip()))


# ═════════════════════════════════════════════════════════════════════
# 7. 把行组装成一道道题
# ═════════════════════════════════════════════════════════════════════
def 拆成题目(所有行):
    """把行列表组装成题目列表。

    返回：[{"题号": "1", "题干": "...", "选项": ["A、...", ...]}, ...]
    """
    题目列表 = []
    当前题 = None
    已进别的区 = False

    for 页码, 行 in 所有行:
        裸 = 行.strip()
        if not 裸:
            continue

        # 到了答案表就停，后面不是题目了
        if 裸.startswith(答案表起点):
            break

        # 碰到填空题这类分界标记，之后不是选择题
        if 裸.startswith(分界标记):
            已进别的区 = True
            当前题 = None
            continue
        if 已进别的区:
            continue

        if 是题目开头(裸):
            题号 = re.match(r"^(\d+)", 裸).group(1)
            当前题 = {"题号": 题号, "题干": 裸, "选项": []}
            题目列表.append(当前题)
        elif 是选项开头(裸):
            if 当前题 is not None:
                # 一行可能塞着多个选项，全挂上
                当前题["选项"].extend(拆开多选项(裸))
        elif 是页眉(裸):
            # 页眉直接丢掉，绝不能接进题干
            continue
        else:
            # 续行：出过选项就接最后一个选项，否则接题干
            if 当前题 is None:
                continue
            if 当前题["选项"]:
                当前题["选项"][-1] += 裸
            else:
                当前题["题干"] += 裸

    return 题目列表


# ═════════════════════════════════════════════════════════════════════
# 8. 体检：每题的选项个数对不对
# ═════════════════════════════════════════════════════════════════════
def 检查选项完整性(题目列表):
    """检查每题选项个数，返回警告列表（空列表 = 全对）。

    CSV 固定 7 列，选项超过 4 个会被丢掉 —— 必须报警，不能静默丢数据。
    """
    警告 = []

    for 题 in 题目列表:
        个数 = len(题["选项"])
        题号 = 题["题号"]

        if 个数 == 0:
            警告.append(f"第 {题号} 题：一个选项都没解析出来")
        elif 个数 > 4:
            警告.append(
                f"第 {题号} 题：解析出 {个数} 个选项，CSV 只放得下 4 个，"
                f"多出来的会被丢弃 → {' / '.join(题['选项'][4:])}"
            )
        elif 个数 < 4:
            警告.append(f"第 {题号} 题：只有 {个数} 个选项（A~D 没占满）")

    return 警告


# ═════════════════════════════════════════════════════════════════════
# 9. 写成 CSV
# ═════════════════════════════════════════════════════════════════════
def 写成CSV(题目列表, csv路径):
    """把题目列表写成 CSV。返回写进去的行数（不含表头）。"""
    try:
        # parents=True：父目录不存在也一起建
        csv路径.parent.mkdir(parents=True, exist_ok=True)
    except OSError as e:
        raise SystemExit(
            f"❌ 建不了输出目录：{csv路径.parent}\n"
            f"   原因：{type(e).__name__}: {e}"
        ) from e

    try:
        # utf-8-sig：Excel 双击打开不乱码
        with open(csv路径, "w", newline="", encoding="utf-8-sig") as f:
            写手 = csv.writer(f)
            写手.writerow(["题号", "题型", "题干", "选项A", "选项B", "选项C", "选项D"])

            for 题 in 题目列表:
                选项 = 题["选项"]
                # 不足 4 个补空串，保证每行都是 7 列
                选项列 = [选项[i] if i < len(选项) else "" for i in range(4)]
                写手.writerow([题["题号"], "选择", 题["题干"], *选项列])
    except PermissionError as e:
        # Windows 上最常见：CSV 正被 Excel 打开着，写不进去
        raise SystemExit(
            f"❌ 没权限写 {csv路径.name}\n"
            f"   原因：{type(e).__name__}: {e}\n"
            f"   多半是这个 CSV 正被 Excel 打开着 —— 关掉 Excel 再跑一次。"
        ) from e
    except OSError as e:
        raise SystemExit(
            f"❌ 写 CSV 失败：{csv路径}\n"
            f"   原因：{type(e).__name__}: {e}"
        ) from e

    return len(题目列表)


# ═════════════════════════════════════════════════════════════════════
# 10. 读回来核对
# ═════════════════════════════════════════════════════════════════════
def 回读校验(csv路径):
    """读回 CSV 核对。返回 (行数, 表头列表)。"""
    try:
        with open(csv路径, "r", newline="", encoding="utf-8-sig") as f:
            读手 = csv.reader(f)
            # next(读手, None)：空文件返回 None，不会抛 StopIteration
            表头 = next(读手, None)
            if 表头 is None:
                raise SystemExit(
                    f"❌ 回读失败：{csv路径.name} 是 0 字节空文件，写的时候就没成功。"
                )
            行数 = sum(1 for _ in 读手)
    except PermissionError as e:
        raise SystemExit(
            f"❌ 回读失败：{csv路径.name} 正被别的程序占着，关掉再试。"
        ) from e
    except UnicodeDecodeError as e:
        raise SystemExit(
            f"❌ 回读失败：{csv路径.name} 解码出错（不是本脚本写的文件？）\n"
            f"   原因：{e}"
        ) from e

    return 行数, 表头


# ═════════════════════════════════════════════════════════════════════
# 11. 主流程
# ═════════════════════════════════════════════════════════════════════
def main():
    print("=" * 60)
    print("📄 课件 PDF → 题库 CSV")
    print("=" * 60)

    print("① 提取所有行…")
    所有行 = 提取所有行(素材PDF)
    print(f"   共 {len(所有行)} 个非空行")

    print("② 拆成题目…")
    题目列表 = 拆成题目(所有行)
    print(f"   共解析出 {len(题目列表)} 道题")

    # 一道题都没有 = 一定哪里坏了，不能装作成功
    # 最典型的假绿：写出一个只有表头的空 CSV，回读校验还"通过"（0 == 0）
    if not 题目列表:
        raise SystemExit(
            "❌ 一道题都没解析出来，不产出 CSV。\n"
            "   可能是题号规则对不上这份 PDF 了。\n"
            "   宁可不产出，也不要写个空表糊弄过去。"
        )

    警告 = 检查选项完整性(题目列表)
    if 警告:
        print(f"   ⚠️ {len(警告)} 道题的选项有问题：")
        for 一条 in 警告:
            print(f"      · {一条}")
    else:
        print("   ✅ 每题选项都齐（4 个）")

    print("③ 写 CSV…")
    行数 = 写成CSV(题目列表, 输出CSV)
    print(f"   已写入 {行数} 行 → {输出CSV}")

    print("④ 回读校验…")
    读回行数, 表头 = 回读校验(输出CSV)
    print(f"   回读 {读回行数} 行，表头 = {表头}")

    # 不用 assert：`python -O` 会把 assert 全部跳过 → 出错也不吭声（假绿）
    期望表头 = ["题号", "题型", "题干", "选项A", "选项B", "选项C", "选项D"]
    if 读回行数 != 行数:
        raise SystemExit(f"❌ 回读行数对不上：写进去 {行数} 行，读回来 {读回行数} 行")
    if 表头 != 期望表头:
        raise SystemExit(f"❌ 表头不对：期望 {期望表头}，实际 {表头}")

    print()
    print("=" * 60)
    print(f"🎉 完成：{行数} 道题已存进 {输出CSV.name}")
    print("=" * 60)

    # 前 3 道题打印出来给你眼看
    print("\n📋 前 3 道题（看看拆得对不对）：\n")
    for 题 in 题目列表[:3]:
        print(f"【第 {题['题号']} 题】{题['题干'][:60]}")
        for 选项 in 题["选项"]:
            print(f"    {选项}")
        print()


if __name__ == "__main__":
    main()
