with open("test.txt", "r", encoding="utf-8") as f:
    # ✅ 这次读对了文件：test.txt（4 行 17 个词）
    # ✅ 只开一次门，后面全在循环里处理 —— 避开指针坑
    行数 = 0
    # 行数 = 0，计数器初始化
    词数 = 0
    # 词数 = 0，计数器初始化
    词频 = {}
    # 词频 = 空字典，准备装 {"apple": 7, ...} 这样的映射
    空白 = 0
    # 空白 = 0，计数器初始化
    for line in f:                      # ← 一次开门，循环里处理
        # 每轮循环拿到一行；整个文件只被"读"一次，不存在指针问题
        行数 += 1
        # 每循环一次说明读到一行，行数 +1
        词 = line.split()
        # split() 不带参数 = 按【所有空白字符】分割，且自动忽略首尾空白
        # 得到一个词列表，例如 ['apple', 'banana', 'apple', 'orange']
        词数 += len(词)
        # 把这行的词数累加到总数里
        for w in 词:
            # 遍历这一行的每个词
            词频[w] = 词频.get(w, 0) + 1
            # ★ 词频统计标准套路（你写对过很多次）：
            #   .get(w, 0) = 字典里没有 w 就返回 0（不报 KeyError）
            #   出现一次就 +1
        if line.strip() == "":          # ← 空白行判断
            # strip() 去掉首尾空白后是空字符串 → 说明这行只有换行符，是空白行
            # 注意：要先 strip() 再判断，直接判 line == "\n" 只对 Unix 换行成立
            空白 += 1
            # 计数 +1

    print("行数", 行数)
    # 答案：4
    print("词数", 词数)
    # 答案：17（4+4+4+5）
    print("空白行", 空白)
    # 答案：0（test.txt 每行都有内容，所以是 0 —— 不是代码错了）
    排好的 = sorted(词频.items(), key=lambda x: x[1], reverse=True)
    # ★ sorted(可迭代对象, key=排序依据, reverse=是否倒序)
    #   .items()   → 把字典拆成 [(键, 值), (键, 值), ...] 一堆元组
    #   key=lambda x: x[1] → 按元组的【第2项】（值=次数）排序
    #   reverse=True → 倒序（多的排前面）；不加就是升序（少的排前面）
    for 词, 次数 in 排好的[:3]:
        # 解包元组：每次拿到 (词, 次数)；[:3] 取前 3 个
        print(词, 次数)
        # 答案：apple 7、banana 4、orange 3
