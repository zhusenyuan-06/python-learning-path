"""
批量重命名文件脚本
==================
功能：把某个目录下，文件名里包含「旧片段」的文件，改成包含「新片段」的名字。

例：
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg
    → 把 D:/照片 下所有 .jpg 文件名里的 "_v1" 换成 "_v2"


═════════════════════════════════════════════════════════════════════════════
【名词表】—— 第一次看这份代码请先扫一遍这里
═════════════════════════════════════════════════════════════════════════════

    Path      pathlib 里的「路径对象」。不是普通字符串，它有一堆好用的方法：
              .name（文件名）、.stem（主体名）、.suffix（扩展名）、
              .parent（父目录）、.exists()（在不在）、.is_file()（是不是文件）、
              .is_dir()（是不是目录）、.iterdir()（列出目录内容）、
              .with_name(新名)（换文件名，目录不变）、.rename(目标)（改名/移动）
              本脚本里所有路径都用 Path，不用字符串拼接。

    路径三段   数据.tar.gz  →  name = "数据.tar.gz"（完整文件名）
                          →  stem = "数据.tar"（主体名，只剥掉【最后】一个扩展名）
                          →  suffix = ".gz"（扩展名，【带点】）

    计划       一份「打算怎么改」的清单，长这样：
              [(旧路径, 新路径), (旧路径, 新路径), ...]
              它的意义是：先把所有事算清楚，【再】动手改。

    成功/失败  执行改名后的两个结果清单：
              成功 = [(旧路径, 新路径), ...]
              失败 = [(旧路径, 失败原因字符串), ...]

    干跑       dry-run，「只看不改」。本脚本默认就是干跑模式。

    冲突       「我想改成的新名字」已经存在了 → 改了会覆盖别人 → 必须跳过。

    占用       文件被别的程序打开着（VSCode / OneDrive / 杀毒软件）→ 改不了。


═════════════════════════════════════════════════════════════════════════════
【安全设计三件套】（这个脚本真正的考点，不是 rename 怎么调）
═════════════════════════════════════════════════════════════════════════════

    ① 干跑默认开（dry-run）
       不加 --apply 就只打印「旧名 → 新名」的计划表，什么都不改。
       原因：批量改名是【不可逆操作】。改错 50 个文件，比没写这个脚本危险得多。

    ② 冲突预检
       目标名已经存在 → 跳过 + 报告，【绝不覆盖】。
       原因：Path.rename() 在目标已存在时的行为【跨平台不一致】：
             Windows → 抛 FileExistsError（拒绝覆盖）
             Linux   → 静默覆盖，原文件内容直接没了
       同一个脚本在 Windows 上给你报错，在别人 Linux 上把文件吞了。
       所以不能依赖 rename 的默认行为，必须自己先检查。

    ③ 操作日志 + 撤销
       每次真改名都记一份「旧名 → 新名」日志，--undo 可以改回去。
       原因：批量操作必须有退路。


═════════════════════════════════════════════════════════════════════════════
【三个已实测的坑】（都在本机 Windows 上跑过，不是听说的）
═════════════════════════════════════════════════════════════════════════════

    坑1  新片段里带路径分隔符（/ 或 \）会怎样？
         → 用 with_name() 拼 → ValueError: Invalid name 'sub/a.txt'
         → 用 目录/新名字 拼 → 如果目标目录【恰好存在】，文件会被静默搬进子目录！
           实测：根目录剩 ['sub']，sub 里出现 ['a.txt']。
           这就是「批量改名」悄悄变成「批量搬家」—— 不报错、不提示、位置变了。
         → 所以【必须挡】：新片段含分隔符就报错退出。

    坑2  文件被别的程序占着 → PermissionError: [WinError 32]
         （VSCode 打开着 / OneDrive 正在同步 / 杀毒软件正在扫）
         这个跟 todo-cli 里 os.replace 踩的 WinError 32 是同一个坑。
         → 所以每个文件单独 try/except，一个失败不影响后面的。

    坑3  边遍历边改名 → 会漏文件
         实测：iterdir() 和 glob() 返回的都是【生成器】，
         一边迭代一边改名，目录内容在变，迭代器可能跳过元素。
         → 所以必须先把要改的【全部收集成列表】，再动手。


═════════════════════════════════════════════════════════════════════════════
【已知限制】（还没做的，明天 11-06 要处理）
═════════════════════════════════════════════════════════════════════════════

    ⚠️ 链式改名冲突：如果目录里有 A.txt → B.txt、B.txt → C.txt 这种
       「A 要改成 B、而 B 也要改成 C」的情况，本脚本会先把 A 改名失败
       （因为 B 还被原文件占着）。两种解法：
         - 两阶段改名：先全改成临时名，再从临时名改成目标名
         - 检测链式并跳过
       这两种都还没做，见 README 的「已知限制」节。

    ⚠️ 不递归子目录：只处理【一层】目录里的文件，子目录里的文件不动
       （这是刻意的设计，见「收集计划」里的注释）


═════════════════════════════════════════════════════════════════════════════
【怎么用】
═════════════════════════════════════════════════════════════════════════════

    # 1. 先看计划（什么都不改）—— 强烈建议每次都先跑这步
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg

    # 2. 确认没问题了，再真改
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg --apply

    # 3. 改错了，撤销
    python batch_rename.py D:/照片 _v1 _v2 --undo 改名日志.log
"""

import argparse                                      # 标准库：解析命令行参数
import sys                                          # 标准库：sys.argv（命令行参数列表）
from pathlib import Path                            # 标准库：路径操作（本脚本的主力工具）

# 日志文件的默认名字（--undo 不指定时用这个）
# ⚠️ 它是【相对路径】，所以会写在「你运行命令时所在的目录」，不是脚本目录。
#    想固定位置的话可以改成 Path(__file__).parent / "改名日志.log"
默认日志 = "改名日志.log"


# ════════════════════════════════════════════════════════════════════════════
# 【第 1 步】收集计划 —— 扫目录，算清楚「谁要改成谁」
# ════════════════════════════════════════════════════════════════════════════
def 收集计划(目录, 旧片段, 新片段, 扩展名):
    """扫描目录，返回要改名的计划列表。

    参数：
        目录     —— 要处理的目录（Path 对象，不是字符串）
        旧片段   —— 文件名里要被替换掉的片段，比如 "_v1"
        新片段   —— 替换成的新片段，比如 "_v2"
        扩展名   —— 只改这个扩展名的文件（如 ".txt"）；None = 全部都改
    返回：
        [(旧路径, 新路径), ...]  —— 计划列表，每个元素是一对「改名前后」

    ⚠️ 坑3：iterdir() 返回的是生成器，所以外面套一层 list() 先收集成实体列表。
            【不要边遍历边改名】，那样会漏文件。
    """
    # ---- 局部变量说明 ----
    # 计划      —— 空的列表，用来装「(旧路径, 新路径)」这种对子
    # p         —— 循环变量，代表当前正在看的那一个文件（Path 对象）
    # 扩展名     —— 参数传进来的是 ".txt" 这种带点的字符串；传 None 表示不限
    # 旧片段     —— 参数，文件名里要找的那一段
    # 新片段     —— 参数，要换上的那一段
    # 新文件名   —— 当前这个文件改完之后应该叫的名字（只是字符串，还没变成路径）
    # 新路径     —— 当前这个文件改完之后应该在哪（Path 对象）

    计划 = []                                        # ① 先准备一个空列表装结果

    # ② 坑3：iterdir() 是生成器 → 先 list() 变成实体列表，再遍历
    #    为什么要 list()：一边迭代一边改名，目录内容在变，迭代器可能漏掉元素
    #    list() 之后就是一个固定的「待办清单」，改多少都不会影响清单本身
    for p in list(目录.iterdir()):
        # ③ 条件①：只要【文件】，文件夹跳过
        #    is_file() 返回 True/False（是个布尔值）
        #    continue = 「这一行不成立，跳过这个，继续下一个」
        if not p.is_file():
            continue

        # ④ 条件②：扩展名要对得上
        #    ⚠️ 扩展名参数是 None 时（默认全部）就【不做这个检查】
        #    ⚠️ 为什么用 and 而不是直接写 p.suffix != 扩展名？
        #       因为扩展名是 None 时，p.suffix != None 【恒为 True】，
        #       那样会把所有文件都过滤掉，一个都改不了。
        #       and 的【短路特性】：左边为假时，右边根本不求值。
        if 扩展名 is not None and p.suffix != 扩展名:
            continue

        # ⑤ 条件③：文件名里确实有旧片段（没有的话改了等于没改）
        #    in 是「包含」运算符，对字符串就是「里面有没有这一段」
        if 旧片段 not in p.name:
            continue

        # ⑥ 条件④：换完确实变了
        #    replace(旧, 新) = 把字符串里的旧片段换成新片段，【替换所有出现】
        #    ⚠️ 找不到旧片段时 replace 会【原样返回】，不报错
        #       所以这条检查是必须的，否则计划里会混进「改名成自己」的项
        新文件名 = p.name.replace(旧片段, 新片段)
        if 新文件名 == p.name:
            continue

        # ⑦ 用 with_name 换掉文件名部分，目录不变
        #    ⚠️ with_name 只接受【纯文件名】，不能带 / 或 \
        #       传 "sub/a.txt" 会报 ValueError: Invalid name
        #    ⚠️ 千万别写成 目录 / 新名字 —— 那样会改变文件所在位置（坑1）
        新路径 = p.with_name(新文件名)

        # ⑧ 把这一对收进计划
        #    append = 往列表末尾加一项
        计划.append((p, 新路径))

    return 计划


# ════════════════════════════════════════════════════════════════════════════
# 【第 2 步】检查冲突 —— 干跑模式下【也要做】
# ════════════════════════════════════════════════════════════════════════════
def 找冲突(计划):
    """找出计划里「目标名已经存在」的项。

    ⚠️ 干跑模式【也要做这个检查】——
       「不执行改名」不等于「不检查」。
       冲突检查是纯只读操作，不动任何文件。
       而且这正是干跑的价值：让你在改之前就看到「有 3 个会冲突」。

    ⚠️ 为什么不用「让 rename 自己报错」来发现冲突？
       因为 Windows 会抛 FileExistsError（报错），
       但 Linux 会【静默覆盖】——文件内容直接没了，不报错。
       主动查一次，才能在两个平台上行为一致。

    返回：
        [(旧路径, 新路径), ...]  —— 会冲突的项
    """
    冲突 = []                        # 空列表，装冲突项

    for 旧, 新 in 计划:              # 把计划里的每一对拆开：旧 = 原路径，新 = 目标路径
        # exists() = 目标路径在磁盘上已经存在吗（True/False）
        if 新.exists():
            冲突.append((旧, 新))    # 收进冲突列表

    return 冲突


# ════════════════════════════════════════════════════════════════════════════
# 【第 3 步】执行改名 —— 真正动文件的地方
# ════════════════════════════════════════════════════════════════════════════
def 执行改名(计划):
    """真正执行改名。

    返回：
        (成功列表, 失败列表)
            成功列表 —— [(旧路径, 新路径), ...]
            失败列表 —— [(旧路径, 失败原因字符串), ...]

    ⚠️ 每个文件单独 try/except —— 一个失败不影响后面的。
       （跟 todo-cli 里 del 命令一个套路：单个失败不中断整体）

    ⚠️ 三个 except 的【顺序不能换】！
       FileExistsError 和 PermissionError 都是 OSError 的【子类】。
       Python 按顺序匹配，命中第一个就停。
       如果把 except OSError 写在前面，它会把前两个也吃掉，
       后面的分支永远走不到。
       【子类必须写在父类前面】—— 这是一条铁律。
    """
    成功 = []                        # 空列表，装改成功的
    失败 = []                        # 空列表，装改失败的

    for 旧, 新 in 计划:
        try:
            # rename(目标) = 改名。这是整个脚本里【唯一】真正改动文件的一行。
            # ⚠️ 它同时也是「移动」—— 目标路径在别处的话，文件就搬到别处去了
            旧.rename(新)

            # 改成功了，记一笔（记的是「旧路径 → 新路径」，撤销时要用）
            成功.append((旧, 新))

        except FileExistsError:
            # 目标已经存在（Linux 上通常不会走到这，因为 Linux 会直接覆盖）
            失败.append((旧, "目标已存在，已跳过（绝不覆盖）"))

        except PermissionError:
            # 文件被别的程序占用（VSCode 开着 / OneDrive 在同步 / 杀毒软件在扫）
            # 这跟 todo-cli 里 os.replace 踩的 WinError 32 是同一个坑
            失败.append((旧, "文件被其他程序占用，已跳过"))

        except OSError as e:
            # 其他系统错误：磁盘满、只读盘、路径太长……
            # as e = 把异常对象存进变量 e，e 就是那个错误对象
            失败.append((旧, f"系统错误：{e}"))

    return 成功, 失败


# ════════════════════════════════════════════════════════════════════════════
# 【第 4 步】写日志 —— 给「撤销」留退路
# ════════════════════════════════════════════════════════════════════════════
def 写日志(成功列表, 日志文件):
    """把「旧名 → 新名」写进日志文件，供 --undo 用。

    参数：
        成功列表 —— [(旧路径, 新路径), ...]
        日志文件 —— 写到哪个文件（Path 对象）

    格式：每行一条，用 tab 分隔
    """
    # "w" = 写模式（不存在就创建，存在就【清空】）—— 跟你 todo-cli 里的一样
    # encoding="utf-8" = 用 UTF-8 存中文，不然 Windows 上会乱码
    with open(日志文件, "w", encoding="utf-8") as f:
        # f = 打开的文件对象（with 会在代码块结束时自动关文件）
        for 旧, 新 in 成功列表:
            # ⚠️ 用 \t（制表符）分隔，【不能】用空格！
            #    因为路径里可能有空格（"C:\Users\15816\My Documents\a.txt"），
            #    用空格分隔的话 split(" ") 会把一个路径拆成两半。
            # \t 是「一个字符」，所以 split("\t") 一定能正确拆开。
            f.write(f"{旧}\t{新}\n")   # f-string = 把 {} 里的变量塞进字符串


# ════════════════════════════════════════════════════════════════════════════
# 【撤销】—— 把改过的名字改回去
# ════════════════════════════════════════════════════════════════════════════
def 读日志撤销(日志文件):
    """读日志，把文件改回原来的名字。

    ⚠️ 撤销时也可能失败（原名被别人占了）——
       跳过 + 报告，继续处理其他的，最后汇总。
    """
    成功 = []
    失败 = []

    # "r" = 只读模式。⚠️ 千万别写成 "w" —— 那会当场清空日志文件！
    #    （这正是你错题本里 E31 / E24 那个坑：open(源, 'w') 把源清空）
    with open(日志文件, "r", encoding="utf-8") as f:
        for 行 in f:
            # strip() = 去掉两端的空白字符（主要是行尾的换行符 \n）
            行 = 行.strip()
            if not 行:               # 空行跳过（文件末尾常有一个空行）
                continue

            # split("\t") = 按 tab 切成两半，拆完是一个【列表】
            # ⚠️ split 最多只能拆成 2 份，所以这里正好拆成两个
            旧, 新 = 行.split("\t")

            # 日志里存的是字符串，要变回 Path 对象才能用 .rename()
            旧 = Path(旧)
            新 = Path(新)

            try:
                # ⚠️⚠️ 方向是【反】的！撤销 = 把【新名】改回【旧名】
                #    日志记的是「旧名 → 新名」，撤销就倒着走。
                #    写反了会「撤销成改名」，越撤越乱。
                新.rename(旧)

                成功.append((新, 旧))    # 撤销成功的记（方向也是反的）

            except FileExistsError:
                # 原名已经被别的文件占着了 → 撤销不了，跳过
                失败.append((新, "原名已被占用，无法撤销"))

            except PermissionError:
                # 文件被别的程序占用
                失败.append((新, "文件被其他程序占用，无法撤销"))

            except OSError as e:
                失败.append((新, f"系统错误：{e}"))

    return 成功, 失败


# ════════════════════════════════════════════════════════════════════════════
# 【主流程】—— 把所有零件串起来
# ════════════════════════════════════════════════════════════════════════════
def main():
    """命令行入口。"""

    # ────────────────────────────────────────────────────────────────────────
    # ⓪ 先看参数够不够 —— 不够就打中文提示，别让 argparse 甩一串英文给用户
    #
    #   sys.argv = 命令行参数列表
    #     argv[0] = 脚本名本身（batch_rename.py）
    #     argv[1] 开始 = 用户敲的内容
    #
    #   本脚本需要 3 个位置参数（目录 旧片段 新片段），
    #   所以 argv 至少要有 4 项（脚本名 + 3 个）。
    #
    #   ⚠️ 例外：--undo 模式【不需要】那 3 个位置参数
    #     撤销只要一个日志文件就够了，所以走的是另一条路。
    #     这里要单独放行，不然 argparse 会报
    #     "the following arguments are required: 目录, 旧片段, 新片段"
    #
    #   ⚠️ 例外：--help 【必须放行】
    #     用户敲 --help 就是想看完整说明，
    #     如果被这个检查拦下来，就只能看到我自己写的那几行了。
    #
    #   ⚠️ 为什么加这一层？
    #     在 PyCharm 里点【运行】按钮，命令行是空的，
    #     直接交给 argparse 会甩一句英文：
    #       "the following arguments are required: 目录, 旧片段, 新片段"
    #     退出码 2。新手看到会以为是程序崩了。
    #     这里先拦一下，给一句人话。
    # ────────────────────────────────────────────────────────────────────────
    是撤销模式 = "--undo" in sys.argv
    是帮助模式 = "--help" in sys.argv or "-h" in sys.argv

    if not 是撤销模式 and not 是帮助模式 and len(sys.argv) < 4:
        print("❌ 参数不够，这个脚本需要 3 个必填参数：")
        print()
        print("   用法：python batch_rename.py <目录> <旧片段> <新片段> [选项]")
        print()
        print("   例子：")
        print('     python batch_rename.py "D:/照片" _v1 _v2 --ext .jpg')
        print("     ↑ 把 D:/照片 下所有 .jpg 文件名里的 _v1 换成 _v2")
        print()
        print("   选项：")
        print("     --ext .txt     只改这个扩展名的文件（默认全部）")
        print("     --apply        真正执行（不加就只打印计划表）")
        print("     --undo 日志     按日志撤销之前的改名")
        print()
        print("   完整说明：python batch_rename.py --help")
        return

    if 是撤销模式 and len(sys.argv) < 3:
        print("❌ --undo 后面要跟日志文件名")
        print()
        print("   用法：python batch_rename.py <目录> <旧片段> <新片段> --undo <日志文件>")
        print("   例子：python batch_rename.py D:/照片 _v1 _v2 --undo 改名日志.log")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ① 解析命令行参数
    #    argparse 帮你干的事：认位置参数、认开关、处理 --help、用户漏参数时自动报错退出
    # ────────────────────────────────────────────────────────────────────────
    parser = argparse.ArgumentParser(
        description="批量重命名文件（把文件名里的旧片段换成新片段）",
        epilog="示例：python batch_rename.py \"D:/照片\" _v1 _v2 --ext .jpg --apply",
    )

    # ---- 位置参数：按顺序对应，用户必须给，少一个 argparse 就自动报错退出 ----
    # ⚠️ nargs="?" 的意思是「这个参数【可以不给】」
    #    默认是 nargs=None（必须给），改了之后不给也不会报错
    #    为什么要改？因为 --undo 模式根本不需要目录和片段，
    #    如果它们是必填的，撤销命令就永远跑不起来。
    parser.add_argument("目录", nargs="?", help="要处理的目录")
    parser.add_argument("旧片段", nargs="?", help="要替换的旧片段")
    parser.add_argument("新片段", nargs="?", help="要替换成的新片段")

    # ---- 开关参数：给了就是 True，不给就是 False ----
    # action="store_true" 的作用：不给时是 False（而不是 None）
    parser.add_argument("--apply", action="store_true",
                        help="真正执行改名（不加就只打印计划）")

    # ---- 带默认值的可选参数 ----
    parser.add_argument("--ext", default=None,
                        help="只改这个扩展名的文件，如 .txt（默认全部）")
    parser.add_argument("--undo", default=None,
                        help="传入日志文件则执行撤销")

    # parse_args() = 真正解析命令行，把结果装进 args 对象
    # args.目录 / args.旧片段 / args.新片段 / args.apply / args.ext / args.undo
    args = parser.parse_args()

    # ────────────────────────────────────────────────────────────────────────
    # ② 撤销模式：走完全不同的另一条路，所以要【提前 return】
    #
    #    ⚠️ 这段必须在检查「目录/片段有没有给」【之前】，
    #       因为撤销根本不需要那三个参数。
    # ────────────────────────────────────────────────────────────────────────
    if args.undo:
        日志文件 = Path(args.undo)

        if not 日志文件.exists():
            print(f"❌ 日志文件不存在：{日志文件}")
            return                       # return = 直接结束 main，不往下走了

        成功, 失败 = 读日志撤销(日志文件)

        print(f"撤销完成：✅ 成功 {len(成功)} 个，❌ 失败 {len(失败)} 个")
        for 名, 原因 in 失败:
            print(f"  ⚠️ {名.name}：{原因}")
        return                           # ← 撤销模式到此结束，不进下面的改名流程

    # ────────────────────────────────────────────────────────────────────────
    # ③ 检查三个必填参数给了没有
    #    上面为了兼容 --undo，把它们都设成了 nargs="?"（可以不给），
    #    所以这里要【手动补一次检查】，把 None 的情况拦下来。
    # ────────────────────────────────────────────────────────────────────────
    if args.目录 is None or args.旧片段 is None or args.新片段 is None:
        print("❌ 参数不够，这个脚本需要 3 个必填参数：<目录> <旧片段> <新片段>")
        print()
        print("   例子：python batch_rename.py \"D:/照片\" _v1 _v2 --ext .jpg")
        print()
        print("   完整说明：python batch_rename.py --help")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ④ 检查目录存不存在、是不是目录
    # ────────────────────────────────────────────────────────────────────────
    # Path(args.目录) = 把命令行拿到的【字符串】变成 Path 对象
    目录 = Path(args.目录)

    if not 目录.exists():
        print(f"❌ 目录不存在：{目录}")
        return

    if not 目录.is_dir():
        print(f"❌ 这不是一个目录：{目录}")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ⑤ 坑1：挡掉带路径分隔符的新片段
    #    不挡的话，文件会被【静默搬进子目录】——不报错、不提示、位置变了
    # ────────────────────────────────────────────────────────────────────────
    if "/" in args.新片段 or "\\" in args.新片段:
        print("❌ 新片段不能包含路径分隔符 / 或 \\")
        print("   否则文件会被搬进子目录，而不是单纯改名")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ⑥ 收集计划 —— 先把所有事算清楚，一个文件都还没动
    # ────────────────────────────────────────────────────────────────────────
    计划 = 收集计划(目录, args.旧片段, args.新片段, args.ext)

    if not 计划:
        print("没有需要改的文件")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ⑦ 找冲突 —— 干跑模式下【也要做】！
    # ────────────────────────────────────────────────────────────────────────
    冲突 = 找冲突(计划)

    # ────────────────────────────────────────────────────────────────────────
    # ⑧ 打印计划表 —— 让用户【看清楚要改什么】再决定
    # ────────────────────────────────────────────────────────────────────────
    print(f"共 {len(计划)} 个文件需要改名，其中 {len(冲突)} 个会冲突\n")

    for 旧, 新 in 计划:
        # 标记 = 这一项会不会冲突
        标记 = "❌ 冲突" if 新.exists() else "✅"
        print(f"  {标记} {旧.name}  →  {新.name}")

    # ────────────────────────────────────────────────────────────────────────
    # ⑨ 没加 --apply 就到此为止（干跑模式）
    # ────────────────────────────────────────────────────────────────────────
    if not args.apply:
        print("\n（以上只是预览，什么都没改。加 --apply 才真正执行）")
        return

    # ────────────────────────────────────────────────────────────────────────
    # ⑩ 真执行 —— 到这里才真的动文件
    # ────────────────────────────────────────────────────────────────────────
    成功, 失败 = 执行改名(计划)

    # ────────────────────────────────────────────────────────────────────────
    # ⑪ 汇报 —— 成功多少、失败多少、为什么失败
    # ────────────────────────────────────────────────────────────────────────
    print(f"\n完成：✅ 成功 {len(成功)} 个，❌ 失败 {len(失败)} 个")

    for 旧, 原因 in 失败:
        print(f"  ⚠️ {旧.name}：{原因}")

    # ────────────────────────────────────────────────────────────────────────
    # ⑫ 写日志 —— 给撤销留退路
    # ────────────────────────────────────────────────────────────────────────
    if 成功:
        写日志(成功, 默认日志)
        print(f"📄 操作日志已写入 {默认日志}（改错了可以 --undo 撤销）")


# ════════════════════════════════════════════════════════════════════════════
# 入口：只有【直接运行这个文件时】才执行 main()
#   被别的文件 import 时不执行（这是 Python 的标准写法）
# ════════════════════════════════════════════════════════════════════════════
if __name__ == "__main__":
    main()
