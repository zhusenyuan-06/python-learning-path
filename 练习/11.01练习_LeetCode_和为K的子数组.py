# 【题目描述】
#
#   给定一个整数数组 nums 和一个整数 k，
#   统计并返回 nums 中「和为 k」的【连续子数组】的个数。
#
#   连续子数组 = 从数组里挑一段连续的、不间断的元素。
#   ⚠️ 子数组必须是连续的，不能跳着选。
#
#   示例 1：
#       输入：nums = [1, 1, 1], k = 2
#       输出：2
#       解释：位置 0-1 的 [1,1]、位置 1-2 的 [1,1]
#             —— 位置不同就算不同的子数组，值一样也要分别算。
#             ⚠️ 注意：[1,1,1] 整段和是 3 不是 2，不算。
#
#   示例 2：
#       输入：nums = [1, 2, 3], k = 3
#       输出：2
#       解释：[1,2]（位置 0-1）和 [3]（位置 2）
#
#   示例 3：
#       输入：nums = [1, -1, 0], k = 0
#       输出：3
