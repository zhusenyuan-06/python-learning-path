def 备份():
    """把 batch_rename.py 复制成 batch_rename_备份.py（已存在就不覆盖）。"""
    if 备份文件.exists():
        print(f"备份已存在，不覆盖：{备份文件.name}")
        return
    shutil.copy2(主脚本, 备份文件)
    print(f"✅ 已备份 → {备份文件.name}")


def 还原():
    """用备份覆盖回主脚本。"""
    if not 备份文件.exists():
        print(f"没有备份文件：{备份文件}")
        return
    shutil.copy2(备份文件, 主脚本)
    print(f"✅ 已还原 → {主脚本.name}")


def 检查主脚本现状():
    """看看当前主脚本里有没有 FileNotFoundError 分支。"""
    文本 = 主脚本.read_text(encoding="utf-8")
    次数 = 文本.count("except FileNotFoundError")
    print(f"主脚本里 `except FileNotFoundError` 出现了 {次数} 次")
    print("  0 次 → 作业还没做")
    print("  2 次 → 两处都加了（执行改名 + 读日志撤销），做对了")
    print("  1 次 → 只加了一处，还有漏的")
    print()
    # 检查顺序对不对：FileNotFoundError 必须在 OSError 前面
    for 函数名 in ["执行改名", "读日志撤销"]:
        起点 = 文本.find(f"def {函数名}")
        if 起点 == -1:
            continue
        片段 = 文本[起点:起点 + 3000]
        位置 = 片段.find("except FileNotFoundError")
        os位置 = 片段.find("except OSError")
        if 位置 == -1:
            print(f"  {函数名}()：❌ 还没有 FileNotFoundError 分支")
        elif os位置 != -1 and 位置 > os位置:
            print(f"  {函数名}()：❌ 顺序错了 —— FileNotFoundError 写在 OSError 后面，永远走不到")
        else:
            print(f"  {函数名}()：✅ 有分支，且顺序正确")


