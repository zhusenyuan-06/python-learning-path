def count_subarrays_slow(nums, k):
    """返回 nums 中和为 k 的连续子数组个数（双循环暴力版）。

    思路：
        外层 for 固定【起点】i
        内层 for 从 i 开始往后一个个扩【终点】j，同时把 nums[j] 加进「和」
        如果「和」等于 k，答案 +1

    为什么这样不重不漏：
        - 内层从 i 开始（不是 i+1）→ 单个元素也算子数组
        - 每个 (i, j) 组合只被访问一次 → 不重复
        - 所有起点都试过了 → 不遗漏

    参数：
        nums  —— 待查找的列表
        k     —— 目标和
    返回：
        int —— 和为 k 的连续子数组个数
    """
    答案 = 0
    for i in range(len(nums)):        # 外层：定起点
        和 = 0                        # 每换一个起点，和重新从 0 开始
        for j in range(i, len(nums)):  # 内层：往后扩终点
            和 += nums[j]             # 扩一个，累一个
            if 和 == k:                # 和 == k → 找到一个
                答案 += 1
    return 答案


# =============================================================================
# 【版本 B · 前缀和 + 字典】—— 11-01 讲解过，已写好；等复习时再自己敲一遍
#
#   ⚠️ 复习时请把下面这段【先注释掉】，然后自己从零敲出来，
#      敲完再打开对照。三个要回想起来的坑写在最下面。
#
#   性能实测（本机，同一份随机数据，两版结果完全一致）：
#          n | 暴力 O(n²) | 字典 O(n) | 快多少倍
#        100 |     0.2 ms |   0.02 ms |    10.7×
#       1000 |    21.1 ms |   0.13 ms |   161.9×
#       4000 |   363.7 ms |   0.59 ms |   616.0×
#      10000 |  2294   ms |   1.36 ms |  1687×
#      → n 每翻一倍，暴力慢 4 倍；字典几乎不变。这是量级差别。
# =============================================================================
def count_subarrays_fast(nums, k):
    """返回 nums 中和为 k 的连续子数组个数（前缀和 + 字典版）。

    思路：
        ① 逐个累加得到当前前缀和（当前和）
        ② 子数组和 = P[j+1] - P[i] = k  →  移项得 P[i] = P[j+1] - k
           所以要找的配对值 = 需要 = 当前和 - k
        ③ 字典「计数」记住每个前缀和值出现过几次 → 查一次就知道答案
        ④ 查完再把自己记进字典（先查后记！）

    参数：
        nums  —— 待查找的列表
        k     —— 目标和
    返回：
        int —— 和为 k 的连续子数组个数
    """
    计数 = {0: 1}  # ← 字典初始必须有一项，别删！
    答案 = 0
    当前和 = 0

    for 数 in nums:
        当前和 += 数  # 1. 算出当前这个位置的前缀和
        需要 = 当前和 - k  # 2. 我需要找的前缀和值
        答案 += 计数.get(需要, 0)  # 3. 之前出现过几次？加几次
        计数[当前和] = 计数.get(当前和, 0) + 1  # 4. 把自己记进字典
    return 答案


# =============================================================================
# 【三个坑】（11-01 讲过，写的时候自己回想）
#   ① 计数 = {0: 1} —— 那个 0 代表 P0（空前缀），不能删，值是 1 不是 0
#      删了它，所有「从下标 0 开始」的子数组全漏
#   ② 先查后记 —— 当前前缀和不能和自己配对（空数组不是合法子数组）
#      调换顺序：[1,-1,0] k=0 会算出 5 而不是 3
#   ③ .get(x, 0) 不能写成 [x] —— key 不存在会 KeyError 崩掉
#      k=2 时第 1 轮必然要查一个不存在的 key，所以用 .get 是必需不是保险
# =============================================================================


# ============================================================================================
# 【附：两数之和的暴力解】—— 11-01 你写的 count_pairs，已抽成函数
#   这段和上面的 count_subarrays_slow 是【同一个模式】：双循环 + i+1 起点。
#   两数之和枚举「两个元素」，本题枚举「一段连续区间」—— 内层起点一个是 i+1、一个是 i。
# ============================================================================================
def count_pairs(nums, target):
    """返回所有和为 target 的下标对。

    参数：
        nums    —— 待查找的列表
        target  —— 目标和
    返回：
        [(i, j), ...]  下标对列表，i < j；找不到返回 []
    """
    结果 = []
    for i in range(len(nums)):
        for j in range(i + 1, len(nums)):
            if nums[i] + nums[j] == target:
                结果.append((i, j))
    return 结果


n = [1, 1, 1]
t = 2
print(count_pairs(n, t))   # 期望 [(0, 1), (1, 2)]
