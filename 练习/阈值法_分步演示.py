# -*- coding: utf-8 -*-
"""
阈值法 · 分步演示
每一步都把中间值打出来，让你看见「阈值」这两个字是怎么冒出来的。

运行方式：PyCharm 里右键本文件 → Run '阈值法_分步演示'
"""

库存 = {"苹果": 5, "香蕉": 9, "梨": 7, "橙子": 5, "西瓜": 4}
前N = 3

print("===== 第 0 步：先看清问题 =====")
print("  要求：库存最多的 3 种水果")
print("  库存 =", 库存)
print("  注意：苹果和橙子都是 5 分 —— 第 3 名是【并列】的")


print()
print("===== 第 1 步：先排序（从高到低）=====")
排序后 = sorted(库存.items(), key=lambda x: x[1], reverse=True)
for 下标, (键, 值) in enumerate(排序后):
    print("   下标 %d   %s = %d" % (下标, 键, 值))
print("   排序后 =", 排序后)
print("   注意每个元素是【元组】：(名字, 数量)")


print()
print("===== 第 2 步：老办法 [:3] 干了什么 =====")
print("   排序后[:3] =", 排序后[:3])
print("   -> 只有 3 个，橙子（同为 5 分）被切掉了")
print("   本质：[:3] 是【按个数截断】—— 只准留 3 行")


print()
print("===== 第 3 步：新思路：不数个数，改数【分数线】 =====")
第N名下标 = 前N - 1
print("   第 %d 名 的下标 = %d - 1 = %d" % (前N, 前N, 第N名下标))
第N名 = 排序后[第N名下标]
print("   排序后[%d] = %r          <- 整个元组" % (第N名下标, 第N名))
阈值 = 第N名[1]
print("   排序后[%d][1] = %d       <- 元组的第 2 项，就是【分数线】" % (第N名下标, 阈值))
print("   解读：第 3 名考了 %d 分，那 >= %d 分的都算进 TOP3" % (阈值, 阈值))


print()
print("===== 第 4 步：按分数线筛 =====")
结果 = []
for 键, 值 in 排序后:
    if 值 >= 阈值:
        结果.append((键, 值))
        print("   %s = %d  →  入选" % (键, 值))
    else:
        print("   %s = %d  →  出局" % (键, 值))
print("   结果 =", 结果, " 共 %d 种" % len(结果))


print()
print("===== 第 5 步：笨办法（一个一个加，遇到明显更小的就停）=====")
笨办法 = []
for 键, 值 in 排序后:
    # 已经拿够前N个，而且这个比最后一个还小 → 说明名次超出 TOP3 了，停
    if len(笨办法) >= 前N and 值 < 笨办法[-1][1]:
        break
    笨办法.append((键, 值))
print("   ", 笨办法, " 共 %d 种" % len(笨办法))
print("   两种写法结果%s" % ("一致 ✅" if 笨办法 == 结果 else "不一致 ❌"))


print()
print("===== 换一组数据试试：并列的更多 =====")
库存2 = {"苹果": 5, "香蕉": 9, "梨": 5, "橙子": 5, "西瓜": 5}
排序2 = sorted(库存2.items(), key=lambda x: x[1], reverse=True)
阈值2 = 排序2[前N - 1][1]
结果2 = [项 for 项 in 排序2 if 项[1] >= 阈值2]
print("   排序后 =", 排序2)
print("   老办法 [:3] =", 排序2[:3], " -> 只剩 3 个，另外两个 5 分的被冤枉了")
print("   阈值法  =", 结果2, " -> %d 个全都算进了 TOP3" % len(结果2))
