"""01 · 课件 PDF → 题库 CSV（项目 v1）

════════════════════════════════════════════════════════════════════
这个脚本干的事（一条链路，三步）：

    读 PDF  →  逐行拆出「题号 / 题干 / 选项」  →  存成 CSV

素材：《计算机网络基础》复习 题-答案版.pdf（8 页，你的真实复习资料）
输出：输出/计算机网络基础_题库.csv
════════════════════════════════════════════════════════════════════

⭐ 你要填的地方只有 3 个函数（标了 ★TODO）：
    1) 提取所有非空行
    2) 判断一行是不是「题目开头」
    3) 判断一行是不是「选项开头」

   三个函数填完，脚本就能跑出真 CSV。

⭐⭐ CSV 的列（表头）是固定的 6 列，别改：
    题号 / 题型 / 题干 / 选项A / 选项B / 选项C / 选项D
    （选项D 存第 4 个；没到 4 个选项就留空）

⭐ 本脚本只做【选择题主干】。答案表、填空题、扫描页识别留给 v2（11-23 重构）。
"""

