def count_pairs(nums, target):
    """找出 nums 中所有和等于 target 的下标对。

    参数：
        nums    —— 待查找的列表（元素应该都是数字）
        target  —— 目标和

    返回：
        [(i, j), ...]  下标对的列表，i < j，按发现顺序排列
        找不到时返回 []（空列表，不是 None）

    说明：
        用双循环暴力找。j 从 i+1 开始，保证：
          - 每一对只找一次（不重复）
          - i 永远小于 j（同一个元素不会跟自己配对）
        时间复杂度 O(n²)，但 n ≤ 100 时完全够用。
    """
    # ---- 防御 ①：nums 必须是列表 ----
    if not isinstance(nums, list):
        return "错误：nums 必须是列表"

    # ---- 防御 ②：target 必须是数字 ----
    if not isinstance(target, (int, float)):
        return "错误：target 必须是数字"

    结果 = []          # 容器：找到的下标对都塞进来
    try:
        for i in range(len(nums)):
            for j in range(i + 1, len(nums)):
                if nums[i] + nums[j] == target:
                    结果.append((i, j))   # ← 改①：塞进容器，不立刻 print
    except TypeError:
        # ---- 防御 ③：列表里有非数字 → 不崩，返回一句人话 ----
        return "错误：列表里有非数字元素"

    # 改②：找不到时返回 []，不是 None —— 调用方能直接 len() / for 循环
    return 结果


