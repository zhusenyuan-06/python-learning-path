if __name__ == "__main__":
    # ---------------------------------------------------------------------
    # 【第 1 组】唯一解的用例 —— 下标是确定的，可以直接比
    #   格式：(numbers, target, 期望下标, 说明)
    # ---------------------------------------------------------------------
    固定用例 = [
        ([2, 7, 11, 15], 9, [0, 1], "示例1：2+7=9"),
        ([2, 3, 4], 6, [0, 2], "示例2：2+4=6"),
        ([-1, 0], -1, [0, 1], "示例3：负数 + 0"),
        ([1, 1], 2, [0, 1], "两个一样的数 1+1=2"),
        ([0, 4, 3, 0], 0, [0, 3], "两头都是 0，0+0=0"),
        ([2, 7, 11, 15], 26, [2, 3], "11+15=26，取最大的一对"),
        ([-3, -2, -1], -5, [0, 1], "全负数：-3 + -2 = -5"),
        ([1000000, 2000000], 3000000, [0, 1], "大数边界：两个数都很大"),
    ]

    # ---------------------------------------------------------------------
    # 【第 2 组】边界 / 无解的用例 —— 期望统一是空列表 []
    #   注意 [5], 5 这种：单个元素不能跟自己配，所以是【无解】
    # ---------------------------------------------------------------------
    边界用例 = [
        ([], 0, "空数组：无解"),
        ([5], 5, "单个元素：不能自己跟自己配 → 无解"),
        ([1], 2, "单个元素：连配对的数都没有 → 无解"),
        ([1, 2], 100, "两数之和远大于 target → 无解"),
        ([1, 2], 0, "两数之和远小于 target → 无解"),
        ([1, 2, 3], 10, "三个数都不够 → 无解"),
        ([-1, -2], -5, "负数不够小 → 无解"),
    ]

