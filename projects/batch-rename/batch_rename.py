"""
批量重命名文件脚本
==================
功能：把某个目录下，文件名里包含「旧片段」的文件，改成包含「新片段」的名字。

例：
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg
    → 把 D:/照片 下所有 .jpg 文件名里的 "_v1" 换成 "_v2"


═════════════════════════════════════════════════════════════════════════════
【名词表】—— 第一次看这份代码请先扫一遍这里
═════════════════════════════════════════════════════════════════════════════

    Path      pathlib 里的「路径对象」。不是普通字符串，它有一堆好用的方法：
              .name（文件名）、.stem（主体名）、.suffix（扩展名）、
              .parent（父目录）、.exists()（在不在）、.is_file()（是不是文件）、
              .is_dir()（是不是目录）、.iterdir()（列出目录内容）、
              .with_name(新名)（换文件名，目录不变）、.rename(目标)（改名/移动）
              本脚本里所有路径都用 Path，不用字符串拼接。

    路径三段   数据.tar.gz  →  name = "数据.tar.gz"（完整文件名）
                          →  stem = "数据.tar"（主体名，只剥掉【最后】一个扩展名）
                          →  suffix = ".gz"（扩展名，【带点】）

    计划       一份「打算怎么改」的清单，长这样：
              [(旧路径, 新路径), (旧路径, 新路径), ...]
              它的意义是：先把所有事算清楚，【再】动手改。

    成功/失败  执行改名后的两个结果清单：
              成功 = [(旧路径, 新路径), ...]
              失败 = [(旧路径, 失败原因字符串), ...]

    干跑       dry-run，「只看不改」。本脚本默认就是干跑模式。

    冲突       「我想改成的新名字」已经存在了 → 改了会覆盖别人 → 必须跳过。

    链式       A.txt 要改成 B.txt、B.txt 要改成 C.txt 这种
              「你要改成的名字，正好是别人的旧名字」的情况。
              这不是冲突（都是自己人），但也不能一个一个改 ——
              必须【两阶段】：先全体改成临时名，再统一改成目标名。

    占用       文件被别的程序打开着（VSCode / OneDrive / 杀毒软件）→ 改不了。


═════════════════════════════════════════════════════════════════════════════
【安全设计三件套】（这个脚本真正的考点，不是 rename 怎么调）
═════════════════════════════════════════════════════════════════════════════

    ① 干跑默认开（dry-run）
       不加 --apply 就只打印「旧名 → 新名」的计划表，什么都不改。
       原因：批量改名是【不可逆操作】。改错 50 个文件，比没写这个脚本危险得多。

    ② 冲突预检
       目标名已经存在 → 跳过 + 报告，【绝不覆盖】。
       原因：Path.rename() 在目标已存在时的行为【跨平台不一致】：
             Windows → 抛 FileExistsError（拒绝覆盖）
             Linux   → 静默覆盖，原文件内容直接没了
       同一个脚本在 Windows 上给你报错，在别人 Linux 上把文件吞了。
       所以不能依赖 rename 的默认行为，必须自己先检查。

    ③ 操作日志 + 撤销
       每次真改名都记一份「旧名 → 新名」日志，--undo 可以改回去。
       原因：批量操作必须有退路。


═════════════════════════════════════════════════════════════════════════════
【三个已实测的坑】（都在本机 Windows 上跑过，不是听说的）
═════════════════════════════════════════════════════════════════════════════

    坑1  新片段里带路径分隔符（/ 或 \）会怎样？
         → 用 with_name() 拼 → ValueError: Invalid name 'sub/a.txt'
         → 用 目录/新名字 拼 → 如果目标目录【恰好存在】，文件会被静默搬进子目录！
           实测：根目录剩 ['sub']，sub 里出现 ['a.txt']。
           这就是「批量改名」悄悄变成「批量搬家」—— 不报错、不提示、位置变了。
         → 所以【必须挡】：新片段含分隔符就报错退出。

    坑2  文件被别的程序占着 → PermissionError: [WinError 32]
         （VSCode 打开着 / OneDrive 正在同步 / 杀毒软件正在扫）
         这个跟 todo-cli 里 os.replace 踩的 WinError 32 是同一个坑。
         → 所以每个文件单独 try/except，一个失败不影响后面的。

    坑3  边遍历边改名 → 会漏文件
         实测：iterdir() 和 glob() 返回的都是【生成器】，
         一边迭代一边改名，目录内容在变，迭代器可能跳过元素。
         → 所以必须先把要改的【全部收集成列表】，再动手。


═════════════════════════════════════════════════════════════════════════════
【已知限制】（还没做的）
═════════════════════════════════════════════════════════════════════════════

    ⚠️ 不递归子目录：只处理【一层】目录里的文件，子目录里的文件不动
       （这是刻意的设计，见「收集计划」里的注释）

    ⚠️ 两阶段改名的副作用：脚本在「阶段1 改临时名」和「阶段2 改目标名」
       之间崩了（断电 / Ctrl+C），磁盘上会留下一堆 __tmp_ 开头的文件。
       它们带原扩展名，人工改回来不难。


═════════════════════════════════════════════════════════════════════════════
【怎么用】
═════════════════════════════════════════════════════════════════════════════

    # 1. 先看计划（什么都不改）—— 强烈建议每次都先跑这步
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg

    # 2. 确认没问题了，再真改
    python batch_rename.py D:/照片 _v1 _v2 --ext .jpg --apply

    # 3. 改错了，撤销
    python batch_rename.py D:/照片 _v1 _v2 --undo 改名日志.log
"""

import argparse                                      # 标准库：解析命令行参数
import errno                                         # 标准库：错误码常量（判断错误是局部的还是全局的）
import sys                                           # 标准库：sys.argv（命令行参数列表）
import uuid                                          # 标准库：生成唯一编号（两阶段改名的临时名要用）
from pathlib import Path                            # 标准库：路径操作（本脚本的主力工具）

# 日志文件的默认名字（--undo 不指定时用这个）
# ⚠️ 它是【相对路径】，所以会写在「你运行命令时所在的目录」，不是脚本目录。
#    想固定位置的话可以改成 Path(__file__).parent / "改名日志.log"
默认日志 = "改名日志.log"


# ════════════════════════════════════════════════════════════════════════════
# 【第 1 步】收集计划 —— 扫目录，算清楚「谁要改成谁」
# ════════════════════════════════════════════════════════════════════════════
def 收集计划(目录, 旧片段, 新片段, 扩展名, 只改结尾):
    """扫描目录，返回要改名的计划列表。

    参数：
        目录     —— 要处理的目录（Path 对象，不是字符串）
        旧片段   —— 文件名里要被替换掉的片段，比如 "_v1"
        新片段   —— 替换成的新片段，比如 "_v2"
        扩展名   —— 只改这个扩展名的文件（如 ".txt"）；None = 全部都改
    返回：
        [(旧路径, 新路径), ...]  —— 计划列表，每个元素是一对「改名前后」

    ⚠️ 坑3：iterdir() 返回的是生成器，所以外面套一层 list() 先收集成实体列表。
            【不要边遍历边改名】，那样会漏文件。
    """
    # ---- 局部变量说明 ----
    # 计划      —— 空的列表，用来装「(旧路径, 新路径)」这种对子
    # p         —— 循环变量，代表当前正在看的那一个文件（Path 对象）
    # 扩展名     —— 参数传进来的是 ".txt" 这种带点的字符串；传 None 表示不限
    # 旧片段     —— 参数，文件名里要找的那一段
    # 新片段     —— 参数，要换上的那一段
    # 新文件名   —— 当前这个文件改完之后应该叫的名字（只是字符串，还没变成路径）
    # 新路径     —— 当前这个文件改完之后应该在哪（Path 对象）

    计划 = []                                        # ① 先准备一个空列表装结果

    # ② 坑3：iterdir() 是生成器 → 先 list() 变成实体列表，再遍历
    #    为什么要 list()：一边迭代一边改名，目录内容在变，迭代器可能漏掉元素
    #    list() 之后就是一个固定的「待办清单」，改多少都不会影响清单本身
    for p in list(目录.iterdir()):
        # ③ 条件①：只要【文件】，文件夹跳过
        #    is_file() 返回 True/False（是个布尔值）
        #    continue = 「这一行不成立，跳过这个，继续下一个」
        if not p.is_file():
            continue

        # ④ 条件②：扩展名要对得上
        #    ⚠️ 扩展名参数是 None 时（默认全部）就【不做这个检查】
        #    ⚠️ 为什么用 and 而不是直接写 p.suffix != 扩展名？
        #       因为扩展名是 None 时，p.suffix != None 【恒为 True】，
        #       那样会把所有文件都过滤掉，一个都改不了。
        #       and 的【短路特性】：左边为假时，右边根本不求值。
        if 扩展名 is not None and p.suffix != 扩展名:
            continue
        # 条件②b：--suffix 模式 —— 只看【主体名】的结尾
        #    p.stem = 主体名（剥掉最后一个扩展名）："报告_v1.txt" → "报告_v1"
        #    endswith(旧片段) = 判断主体名是不是以旧片段结尾
        #    ⚠️ 为什么不能看 p.name？文件名带扩展名，"报告_v1.txt".endswith("_v1") 是 False！
        #    ⚠️ and 短路：只改结尾=False 时右边根本不求值 → 不加 --suffix 时行为完全不变
        if 只改结尾 and not p.stem.endswith(旧片段):
            continue


        # ⑤ 条件③：文件名里确实有旧片段（没有的话改了等于没改）
        #    in 是「包含」运算符，对字符串就是「里面有没有这一段」
        if 旧片段 not in p.name:
            continue

        # ⑥ 条件④：换完确实变了
        #    replace(旧, 新) = 把字符串里的旧片段换成新片段，【替换所有出现】
        #    ⚠️ 找不到旧片段时 replace 会【原样返回】，不报错
        #       所以这条检查是必须的，否则计划里会混进「改名成自己」的项
        新文件名 = p.name.replace(旧片段, 新片段)
        if 新文件名 == p.name:
            continue

        # ⑦ 用 with_name 换掉文件名部分，目录不变
        #    ⚠️ with_name 只接受【纯文件名】，不能带 / 或 \
        #       传 "sub/a.txt" 会报 ValueError: Invalid name
        #    ⚠️ 千万别写成 目录 / 新名字 —— 那样会改变文件所在位置（坑1）
        新路径 = p.with_name(新文件名)

        # ⑧ 把这一对收进计划
        #    append = 往列表末尾加一项
        计划.append((p, 新路径))

    return 计划


# ════════════════════════════════════════════════════════════════════════════
# 【第 2 步】检查冲突 —— 干跑模式下【也要做】
# ════════════════════════════════════════════════════════════════════════════
def 牵连(项, 组):
    """判断某一项跟组里某一项有没有「撞名」的牵连关系。

    牵连 = 你的【新名字】正好是别人的【旧名字】（或者反过来）。

    例：A.txt→B.txt、B.txt→C.txt
        A 的新名是 B 的旧名 → A 和 B 牵连 → 必须【一起】挪。
    """
    旧, 新 = 项
    for 组旧, 组新 in 组:
        # 新 == 别人的旧   或   旧 == 别人的新  → 互相撞名
        if 新 == 组旧 or 旧 == 组新:
            return True
    return False


def 找牵连组(计划):
    """把「会互相牵连」的项分到同一组。

    返回：[[项, 项, ...], ...]
        每组是要「一起改」的文件。
        一组里只有 1 个 → 独立文件 → 单阶段改就够了。
        一组里 2 个以上 → 链式 → 必须两阶段改。

    ⚠️ 为什么必须分组？
       单阶段改一组里的两个文件会失败：
         先改 A→B：B 还没挪走 → 撞车报错
         先改 B→C：能成 → 但这叫「碰巧对」，顺序一变就又炸
       「碰巧能跑通」≠「设计正确」。
    """
    组列表 = []                        # 装所有组
    剩余 = list(计划)                  # 还没分组的项

    while 剩余:
        # 取一个还没分组的项当「种子」，开一个新组
        种子 = 剩余.pop(0)
        组 = [种子]

        # 反复吸收：组里每加进一个新项，它可能又跟别的项牵连（链式是传递的）
        # ⚠️ 必须用「循环 + 标记」，只遍历一遍会漏
        # ⚠️ 遍历 list(剩余) 的【复制版】—— 因为循环体里会 remove 剩余
        #    （跟坑3「边遍历边改会漏」一个道理）
        继续吸 = True
        while 继续吸:
            继续吸 = False
            for 项 in list(剩余):
                if 牵连(项, 组):
                    组.append(项)
                    剩余.remove(项)
                    继续吸 = True

        组列表.append(组)

    return 组列表


def 找冲突(计划, 占用原因="目标已存在，已跳过（绝不覆盖）"):
    """找出计划里「不能改」的项，并说明为什么。

    ⚠️ 干跑模式【也要做这个检查】——
       「不执行改名」不等于「不检查」。
       冲突检查是纯只读操作，不动任何文件。
       而且这正是干跑的价值：让你在改之前就看到「有 3 个会冲突」。

    ⚠️ 为什么不用「让 rename 自己报错」来发现冲突？
       因为 Windows 会抛 FileExistsError（报错），
       但 Linux 会【静默覆盖】——文件内容直接没了，不报错。
       主动查一次，才能在两个平台上行为一致。

    🔑 「目标名已经存在」有两种完全不同的性质，必须分开处理：

       ① 组内占用 —— 占着目标名的那个文件【正好是同一组的另一个文件】
          → 是自己人！例：A.txt→B.txt、B.txt→C.txt
          → 这不是冲突，是「要一起改」→ 交给【两阶段改名】处理

       ② 组外占用 —— 占着目标名的那个文件【不在这一组里】
          → 是外部文件，跟本次改名无关 → 必须【跳过】，绝不覆盖

    ⚠️ 一组是「全有或全无」的：
       组里只要有一项撞了【外部文件】→ 整组都做不了。
       例：A.txt→B.txt、B.txt→C.txt，但外面已经有一个 C.txt
           → B→C 做不了 → B 就不会挪走 → A→B 也做不了
       （所以冲突要【按组】判，不能一项一项孤立地判）

    参数：
        计划     —— [(旧路径, 新路径), ...] 待执行的计划
        占用原因 —— 冲突时写进失败清单的说明文字
                    （撤销模式会传「原名已被占用，无法撤销」）
    返回：
        (真冲突列表, 可执行组列表)
            真冲突   —— [(旧路径, 新路径, 原因), ...]  做不了的项
            可执行组 —— [[项, 项, ...], ...]  每组是要「一起改」的文件
    """
    # ═══ 先查「重名目标」：计划自己内部有没有撞车 ═══
    # ⚠️ 例：旧片段 "a" → 新片段 "" 时，"a.txt" 和 "aa.txt" 都变成 ".txt"
    #    两个文件抢同一个名字 → 第二个会撞上第一个
    #    Linux 上更糟：静默覆盖，第一个文件的内容直接没了
    #    这种【计划本身就错了】→ 全部标成冲突，不执行
    # 字典 = {目标路径: 计划里有几个文件指向它}
    目标计数 = {}
    for 旧, 新 in 计划:
        目标计数[新] = 目标计数.get(新, 0) + 1
    # 集合推导式：挑出「被两个以上文件盯着」的目标名
    重名目标 = {新 for 新, 次数 in 目标计数.items() if 次数 > 1}

    真冲突 = []                       # 做不了的项 [(旧, 新, 原因), ...]
    可执行组 = []                     # 能做的组

    for 组 in 找牵连组(计划):
        # 这一组里所有「旧名」—— 用来判断占位的是不是自己人
        # ⚠️ 集合推导式 {旧 for 旧, 新 in 组}：一句式子建集合
        #    Path 可以放进集合（可哈希），而且查找比列表快
        组内旧名 = {旧 for 旧, 新 in 组}
        组冲突 = {}                   # {旧路径: 冲突原因} 这一组里的问题项

        for 旧, 新 in 组:
            # 雷 1：计划内部重名 → 这个目标名有多个文件抢
            if 新 in 重名目标:
                组冲突[旧] = "计划里有多个文件指向同一个目标名，需先手动改开"
                continue

            # exists() = 目标路径在磁盘上已经存在吗（True/False）
            if not 新.exists():
                continue               # 目标不存在 → 没人挡 → 没问题

            if 新 in 组内旧名:
                continue               # 占位的是【组内】另一个文件 → 链式，不是冲突

            # 占位的是【组外】的文件 → 真冲突 → 绝不覆盖
            组冲突[旧] = 占用原因

        if 组冲突:
            # ⚠️ 整组都做不了 → 组里每一项都要报出来（不能只报撞上的那一项）
            #    真正撞上的那个说自己的原因，其他组员说「被同组拖累」
            for 旧, 新 in 组:
                if 旧 in 组冲突:
                    原因 = 组冲突[旧]
                else:
                    原因 = "同组有文件撞名，整组无法执行（绝不覆盖）"
                真冲突.append((旧, 新, 原因))
        else:
            可执行组.append(组)        # 这一组可以执行

    return 真冲突, 可执行组


# ════════════════════════════════════════════════════════════════════════════
# 【第 3 步】执行改名 —— 真正动文件的地方
# ════════════════════════════════════════════════════════════════════════════
def 执行改名(计划, 占用原因="目标已存在，已跳过（绝不覆盖）"):
    """真正执行改名（分岔器：先查冲突，再按组选路线）。

    返回：
        (成功列表, 失败列表, 全局停止)
            成功列表 —— [(旧路径, 新路径), ...]
            失败列表 —— [(旧路径, 失败原因字符串), ...]
            全局停止 —— True = 撞上全局错误，后面不再继续

    ⚠️ 三个 except 的【顺序不能换】！
       FileExistsError 和 PermissionError 都是 OSError 的【子类】。
       Python 按顺序匹配，命中第一个就停。
       如果把 except OSError 写在前面，它会把前两个也吃掉，
       后面的分支永远走不到。
       【子类必须写在父类前面】—— 这是一条铁律。

    🔀 三条路线：
       ① 真冲突项      → 直接记失败（绝不覆盖），不执行
       ② 独立文件组    → 单阶段：直接 旧名 → 新名
       ③ 链式文件组    → 两阶段：先全改临时名，再全改目标名
    """
    成功 = []                        # 空列表，装改成功的
    失败 = []                        # 空列表，装改失败的
    全局停止 = False                 # 默认 False（一路跑完，没被打断）

    # ① 先查冲突（纯只读，不动文件）
    #    ⚠️ 这里【重新查一遍】，不能信 main 里那次 ——
    #    中间可能隔了几秒，磁盘状态变了（TOCTOU）
    真冲突, 组列表 = 找冲突(计划, 占用原因)

    # ② 真冲突的项 → 直接记失败，不执行
    for 旧, 新, 原因 in 真冲突:
        失败.append((旧, 原因))

    # ③ 按组执行
    for 组 in 组列表:
        if len(组) == 1:
            # 独立文件 → 单阶段
            组成功, 组失败, 组停止 = 执行改名_单阶段(组)
        else:
            # 链式文件（组里 2 个以上）→ 两阶段
            组成功, 组失败, 组停止 = 执行改名_两阶段(组)

        成功.extend(组成功)           # extend = 把这一组的结果并进总结果
        失败.extend(组失败)

        if 组停止:
            全局停止 = True
            break                     # 全局错误 → 后面的组都不做了

    return 成功, 失败, 全局停止


# ════════════════════════════════════════════════════════════════════════════
# 【路线 1】单阶段改名 —— 独立文件
# ════════════════════════════════════════════════════════════════════════════
def 执行改名_单阶段(组):
    """单阶段：一个一个直接改成目标名。

    适用：组里只有 1 个文件（不跟别人牵扯），改完就完事。

    返回：(成功列表, 失败列表, 全局停止)
    """
    成功 = []
    失败 = []
    全局停止 = False

    for 旧, 新 in 组:
        try:
            # ⚠️ 动手前再查一次 exists()
            #    前面 找冲突 时查过一次，但中间可能隔了一小会儿，
            #    别人这时建了个同名文件 → 撞上了
            #    自己查 = 两个平台行为一致（Linux 会【静默覆盖】！）
            if 新.exists():
                失败.append((旧, "目标已存在，已跳过（绝不覆盖）"))
                continue

            # rename(目标) = 改名。这是整个脚本里【唯一】真正改动文件的一行。
            # ⚠️ 它同时也是「移动」—— 目标路径在别处的话，文件就搬到别处去了
            旧.rename(新)

            # 改成功了，记一笔（记的是「旧路径 → 新路径」，撤销时要用）
            成功.append((旧, 新))

        except FileNotFoundError:
            # 源文件在【执行的那一刻】已经不在了
            # 典型场景：干跑时文件还在 → 你在 PyCharm 里手动删了 → 再点 --apply
            # 这叫 TOCTOU：检查和使用之间，文件没了
            失败.append((旧, "源文件在执行时不见了，已跳过"))

        except FileExistsError:
            # 目标已经存在（Linux 上通常不会走到这，因为 Linux 会直接覆盖）
            失败.append((旧, "目标已存在，已跳过（绝不覆盖）"))

        except PermissionError:
            # 文件被别的程序占用（VSCode 开着 / OneDrive 在同步 / 杀毒软件在扫）
            # 这跟 todo-cli 里 os.replace 踩的 WinError 32 是同一个坑
            失败.append((旧, "文件被其他程序占用，已跳过"))

        except OSError as e:
            # 其他系统错误：磁盘满、只读盘、路径太长……
            # as e = 把异常对象存进变量 e，e 就是那个错误对象
            if e.errno == errno.ENOSPC:  # 磁盘满 → 全局错误
                失败.append((旧, "磁盘已满（全局错误），已停止"))
                全局停止 = True  # 记下"我是被全局错误打断的"
                break  # 跳出【整个循环】
            if e.errno == errno.EROFS:  # 只读文件系统 → 全局错误
                失败.append((旧, "文件系统只读（全局错误），已停止"))
                全局停止 = True
                break
            失败.append((旧, f"系统错误：{e}"))  # 其余照旧：跳过继续

    return 成功, 失败, 全局停止


# ════════════════════════════════════════════════════════════════════════════
# 【路线 2】两阶段改名 —— 链式文件（任务 4 的核心）
# ════════════════════════════════════════════════════════════════════════════
def 执行改名_两阶段(组):
    """两阶段：专门解决「A→B、B→C」这种互相占位的情况。

    🎯 为什么单阶段会失败？
       目录里有 A.txt 和 B.txt，计划是 A.txt→B.txt、B.txt→C.txt。
         先改 A→B：B.txt 还被原文件占着 → FileExistsError
         先改 B→C：能成 → 但这叫「碰巧对」，目录里文件一多顺序就变了，就又炸
       「碰巧对」不是设计，是运气 → 必须两阶段。

    🔀 两阶段怎么做？
         阶段 1：所有文件【先】改成唯一临时名（A→tmp1、B→tmp2）
                 → 谁都不占谁的位置，不会撞车
         阶段 2：再【统一】从临时名改成目标名（tmp1→B、tmp2→C）
                 → 这时候目标位置全空着，改谁都行

    ⚠️ 要【整组一起】成功，或者【整组一起】失败。
       一半成功一半失败 = 文件名对不上，比全失败还糟。
       所以任何一个文件出问题 → 整组回滚（临时名全改回原名）。

    ⚠️ 副作用：脚本如果在阶段 1 和阶段 2 之间崩了（断电 / Ctrl+C），
       磁盘上会留下一堆 __tmp_ 开头的文件。
       它们的扩展名还在，人工改回来不难。

    返回：(成功列表, 失败列表, 全局停止)
    """
    成功 = []
    失败 = []
    全局停止 = False

    # ═══ 阶段 1：所有文件先改成唯一临时名 ═══
    # 临时映射 = [(旧路径, 临时路径, 最终路径), ...]
    #   为什么要记三样：原名（回滚用）、临时名（现在在哪）、最终名（要去哪）
    临时映射 = []
    阶段1出错 = []                   # [(旧路径, 原因), ...]

    for 旧, 新 in 组:
        # 临时名 = __tmp_<12位随机数><原扩展名>
        # ⚠️ 为什么用随机数：临时名必须【全组唯一】
        #    固定名（__tmp_1）只适合 1 个文件，第 2 个就撞了
        # ⚠️ 为什么保留扩展名：有些工具靠扩展名认类型（.jpg 变 .tmp 就打不开了）
        临时 = 旧.with_name(f"__tmp_{uuid.uuid4().hex[:12]}{旧.suffix}")

        try:
            旧.rename(临时)
            临时映射.append((旧, 临时, 新))

        except FileNotFoundError:
            阶段1出错.append((旧, "源文件在执行时不见了"))
            break                     # 整组一起回滚

        except PermissionError:
            阶段1出错.append((旧, "文件被其他程序占用"))
            break

        except OSError as e:
            if e.errno == errno.ENOSPC:
                阶段1出错.append((旧, "磁盘已满（全局错误）"))
                全局停止 = True
                break
            if e.errno == errno.EROFS:
                阶段1出错.append((旧, "文件系统只读（全局错误）"))
                全局停止 = True
                break
            阶段1出错.append((旧, f"系统错误：{e}"))
            break

    # 阶段 1 就出错 → 整组回滚
    if 阶段1出错:
        回滚临时名(临时映射, [])
        return [], 汇总组失败(组, 阶段1出错), 全局停止

    # ═══ 阶段 2：从临时名统一改成目标名 ═══
    已完成 = []                      # [(临时路径, 最终路径), ...] 阶段 2 改成的
    阶段2出错 = []

    for 旧, 临时, 新 in 临时映射:
        try:
            # ⚠️ 这里必须再查一次 exists()
            #    阶段 1 和阶段 2 之间隔了几毫秒，
            #    别人这时建了个同名文件 → 撞上了
            #    自己查 = 两个平台行为一致（Linux 会【静默覆盖】！）
            if 新.exists():
                阶段2出错.append((旧, "目标已存在（执行中途被占了），已回滚"))
                break

            临时.rename(新)
            已完成.append((临时, 新))
            成功.append((旧, 新))    # 记的是【旧名 → 最终名】，不是临时名

        except FileNotFoundError:
            阶段2出错.append((旧, "临时文件不见了"))
            break

        except FileExistsError:
            阶段2出错.append((旧, "目标已存在，已回滚"))
            break

        except PermissionError:
            阶段2出错.append((旧, "文件被其他程序占用，已回滚"))
            break

        except OSError as e:
            if e.errno == errno.ENOSPC:
                阶段2出错.append((旧, "磁盘已满（全局错误）"))
                全局停止 = True
                break
            if e.errno == errno.EROFS:
                阶段2出错.append((旧, "文件系统只读（全局错误）"))
                全局停止 = True
                break
            阶段2出错.append((旧, f"系统错误：{e}"))
            break

    # 阶段 2 出错 → 整组回滚
    if 阶段2出错:
        回滚临时名(临时映射, 已完成)
        return [], 汇总组失败(组, 阶段2出错), 全局停止

    return 成功, 失败, 全局停止


# ════════════════════════════════════════════════════════════════════════════
# 【辅助】整组失败汇总 —— 一组失败时，给每个组员都一条说法
# ════════════════════════════════════════════════════════════════════════════
def 汇总组失败(组, 出错项):
    """一组失败时，生成整组的失败清单。

    参数：
        组     —— [(旧路径, 新路径), ...] 这一组所有文件
        出错项 —— [(旧路径, 原因), ...] 真正出错的那一个（或几个）
    返回：
        [(旧路径, 原因字符串), ...]  长度 = 组长

    ⚠️ 为什么不给「出错的那个」也套统一说法？
       因为出错的【原因】才是用户真正需要的信息
       （被占用？磁盘满？还是中途被占了？）。
       其他组员只需要知道「不是我这个文件的锅，是同组拖累的」。
    """
    结果 = []
    出错旧名 = {旧 for 旧, _ in 出错项}
    # 第一个出错项的原因 = 这一组的失败原因
    原因 = 出错项[0][1] if 出错项 else "未知原因"

    for 旧, 新 in 组:
        if 旧 in 出错旧名:
            结果.append((旧, 原因))
        else:
            结果.append((旧, "因同组文件失败，整组已回滚（本文件未改动）"))

    return 结果


# ════════════════════════════════════════════════════════════════════════════
# 【辅助】回滚临时名 —— 把两阶段改到一半的结果退回去
# ════════════════════════════════════════════════════════════════════════════
def 回滚临时名(临时映射, 已完成):
    """把两阶段改名退回去（失败时收拾残局用）。

    参数：
        临时映射 —— [(旧路径, 临时路径, 最终路径), ...] 阶段 1 改成的
        已完成   —— [(临时路径, 最终路径), ...]       阶段 2 改成的

    ⚠️ 顺序【不能反】：
       先撤阶段 2（最终名 → 临时名），再撤阶段 1（临时名 → 原名）。
       反过来做会撞名 —— 因为阶段 2 的成果占着某些人的原名。
       例：A→B、B→C，阶段 2 改成了 tmp1→B、tmp2→C。
          撤的时候必须先 C→tmp2、B→tmp1，把名字都腾出来，再 tmp→原名。

    ⚠️ 撤不回来怎么办？只能如实报告。
       极端情况：撤的时候原名被别人占了 → 这个文件就停在临时名上了。
       临时名带原扩展名，人工改回来不难。
    """
    # ① 撤阶段 2：最终名 → 临时名（逆序撤更安全）
    for 临时, 最终 in reversed(已完成):
        try:
            if 最终.exists():
                最终.rename(临时)
        except OSError:
            pass                      # 撤不回来也只能算了，交给报告

    # ② 撤阶段 1：临时名 → 原名
    for 旧, 临时, 新 in 临时映射:
        try:
            if 临时.exists():
                临时.rename(旧)
        except OSError:
            pass


# ════════════════════════════════════════════════════════════════════════════
# 【第 4 步】写日志 —— 给「撤销」留退路
# ════════════════════════════════════════════════════════════════════════════
def 写日志(成功列表, 日志文件):
    """把「旧名 → 新名」写进日志文件，供 --undo 用。

    参数：
        成功列表 —— [(旧路径, 新路径), ...]
        日志文件 —— 写到哪个文件（Path 对象）

    格式：每行一条，用 tab 分隔
    """
    # "w" = 写模式（不存在就创建，存在就【清空】）—— 跟你 todo-cli 里的一样
    # encoding="utf-8" = 用 UTF-8 存中文，不然 Windows 上会乱码
    with open(日志文件, "w", encoding="utf-8") as f:
        # f = 打开的文件对象（with 会在代码块结束时自动关文件）
        for 旧, 新 in 成功列表:
            # ⚠️ 用 \t（制表符）分隔，【不能】用空格！
            #    因为路径里可能有空格（"C:\Users\15816\My Documents\a.txt"），
            #    用空格分隔的话 split(" ") 会把一个路径拆成两半。
            # \t 是「一个字符」，所以 split("\t") 一定能正确拆开。
            f.write(f"{旧}\t{新}\n")   # f-string = 把 {} 里的变量塞进字符串


# ════════════════════════════════════════════════════════════════════════════
# 【撤销】—— 把改过的名字改回去
# ════════════════════════════════════════════════════════════════════════════
def 读日志撤销(日志文件):
    """读日志，把文件改回原来的名字。

    ⚠️ 撤销时也可能失败（原名被别人占了）——
       跳过 + 报告，继续处理其他的，最后汇总。

    🔑 关键设计：撤销【不自己写一套改名逻辑】，而是复用「执行改名」。
       为什么？因为撤销也可能撞车！

       正着改：A.txt→B.txt、B.txt→C.txt（链式）
       倒着撤：B.txt→A.txt、C.txt→B.txt（还是链式！）

       如果撤销自己写一套单阶段逻辑，遇到链式就会撞车撤不回来。
       所以这里只负责「把日志翻译成一份撤销计划」，
       剩下的活儿全交给 执行改名 —— 它自己会分组、自己会两阶段。
    """
    # ① 先把日志读成「撤销计划」
    #    日志记的是「旧名 → 新名」，撤销要【反过来】：「新名 → 旧名」
    #    ⚠️ 方向反了会把「撤销」变成「再改一次」，越撤越乱
    撤销计划 = []

    # "r" = 只读模式。⚠️ 千万别写成 "w" —— 那会当场清空日志文件！
    #    （这正是你错题本里 E31 / E24 那个坑：open(源, 'w') 把源清空）
    with open(日志文件, "r", encoding="utf-8") as f:
        for 行 in f:
            # strip() = 去掉两端的空白字符（主要是行尾的换行符 \n）
            行 = 行.strip()
            if not 行:               # 空行跳过（文件末尾常有一个空行）
                continue

            # ⚠️ 格式不对的行（没有 tab）直接跳过，别让整个撤销崩掉
            if "\t" not in 行:
                continue

            # split("\t") = 按 tab 切成两半，拆完是一个【列表】
            # ⚠️ split 最多只能拆成 2 份，所以这里正好拆成两个
            旧, 新 = 行.split("\t")

            # 日志里存的是字符串，要变回 Path 对象才能用 .rename()
            # ⚠️ 顺序是【反】的：日志记「旧→新」，撤销要「新→旧」
            撤销计划.append((Path(新), Path(旧)))

    if not 撤销计划:
        return [], [], False

    # ② 交给「执行改名」统一处理
    #    它会自己：找冲突 → 分组 → 单阶段 or 两阶段 → 写日志
    #    ⚠️ 撤销的冲突提示要说「原名已被占用」，跟正着改不一样
    return 执行改名(撤销计划, "原名已被占用，无法撤销")


