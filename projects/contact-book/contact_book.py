"""
通讯录 —— 数据层 + 命令行入口

【为什么要把函数改成"接受 dict 参数"】
原来 5 个函数写死操作全局 lianxiren，而且文件一 import 就执行一堆裸 print。
Streamlit 每次点按钮都会把脚本从上到下重跑一遍 —— 不改的话：
  ① 数据每次被重置回初始值（增删改白做）
  ② 控制台疯狂刷屏
改成函数接受 contacts 参数后，CLI 和 Web 各管各的数据，共用同一套增删改查逻辑。

【状态】main() 的 5 处 TODO 已由助手代填并讲透；仍需本人脱稿讲清 session_state 才能销账。
"""

# 初始数据（你原来的 lianxiren，改名避免和函数参数重名）
初始通讯录 = {
    "小明": {"电话": "13800138000", "地址": "海淀区", "邮箱": "xm@mail.com"},
    "小红": {"电话": "13900139000", "地址": "朝阳区", "邮箱": "xh@mail.com"},
}


# ===================================================================
# 数据层：5 个函数（你原来的逻辑，只把 lianxiren 换成参数 contacts）
# ===================================================================

def 查询(contacts, 姓名, 字段):
    """查某人的某个字段。人不在→'查无此人'；字段没填→'未填写'"""
    信息 = contacts.get(姓名)          # 安全查：人不在返回 None
    if 信息 is None:                   # 人不在
        return "查无此人"
    return 信息.get(字段, "未填写")    # 安全查：字段没填返回默认值


def 添加(contacts, 姓名, 电话, 地址, 邮箱=""):
    """加联系人。已存在则不覆盖；邮箱可以不填（字段不统一）"""
    if 姓名 in contacts:               # 防覆盖：先看有没有
        return f"{姓名} 已经在通讯录里了，未覆盖"
    信息 = {"电话": 电话, "地址": 地址}
    if 邮箱:                           # 只有填了邮箱才加这个字段
        信息["邮箱"] = 邮箱
    contacts[姓名] = 信息              # 一次性塞进外层
    return f"已添加 {姓名}"


def 删除(contacts, 姓名):
    """删联系人。人不在→'查无此人'"""
    if 姓名 not in contacts:
        return "查无此人"
    被删 = contacts.pop(姓名)          # pop 会把删掉的东西还给你
    return f"已删除 {姓名}：{被删}"


def 统计未填邮箱(contacts):
    """统计没填邮箱的人，返回 (名单, 人数)"""
    名单 = [姓名 for 姓名, 信息 in contacts.items() if "邮箱" not in 信息]
    return 名单, len(名单)


def 打印通讯录(contacts):
    """双层遍历：外层拿人，内层拿这个人的字段"""
    for 姓名, 信息 in contacts.items():
        print(f"【{姓名}】")
        for 字段, 值 in 信息.items():
            print(f"  {字段}: {值}")


# ===================================================================
# 命令行入口
# ===================================================================

def main():
    """命令行菜单。数据只在内存里，退出程序就没了（Web 版用 session_state 解决）"""
    通讯录 = dict(初始通讯录)   # 拷贝一份，别改初始数据

    # TODO 1 + 2：菜单循环 + 分支调用（两处写在一起，因为分支必须在循环体内）
    while True:
        print("\n===== 通讯录 =====")
        print("1 查询   2 添加   3 删除   4 统计未填邮箱   5 打印全部   0 退出")
        选项 = input("请选择: ").strip()

        if 选项 == "0":
            print("再见")
            break
        elif 选项 == "1":
            姓名 = input("姓名: ")
            字段 = input("字段(电话/地址/邮箱): ")
            print(查询(通讯录, 姓名, 字段))
        elif 选项 == "2":
            姓名 = input("姓名: ")
            电话 = input("电话: ")
            地址 = input("地址: ")
            邮箱 = input("邮箱(可不填): ")
            print(添加(通讯录, 姓名, 电话, 地址, 邮箱))
        elif 选项 == "3":
            姓名 = input("姓名: ")
            print(删除(通讯录, 姓名))
        elif 选项 == "4":
            名单, 人数 = 统计未填邮箱(通讯录)
            print(f"没填邮箱的: {名单} 共 {人数} 人")
        elif 选项 == "5":
            打印通讯录(通讯录)
        else:
            print("无效选项，请重新输入")


if __name__ == "__main__":
    main()
