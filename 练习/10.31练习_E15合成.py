import re
停用词 = {"这个", "的", "了", "得", "是", "在"}

def 热词统计(文本, n=3):
    """弹幕热词统计器：清洗链四步 + reverse + 优雅分支。
    正常情况返回 TOP n 的 [(词, 次数), ...]。
    一个有效词都没有时，返回 []（不能崩、不能算出空串 ''）。
    """
    counts = {}
    for w in re.findall(r'[一-鿿]+|[A-Za-z0-9]+', 文本):
        w = w.lower().strip(".,!?，。！？")
        if not w:
            continue
        if w in 停用词:
            continue
        counts[w] = counts.get(w, 0) + 1
    return sorted(counts.items(), key=lambda x: x[1], reverse=True)[:n]



