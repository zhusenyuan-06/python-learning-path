class Solution:
    """LeetCode 242 · 有效的字母异位词 —— 字典计数法（一个 dict 加一减一）"""

    def isAnagram(self, s: str, t: str) -> bool:
        # ---- 变量说明 ----
        # d   ：字符 → 出现次数 的计数表。s 和 t【共用】这一个字典，
        #       这样两边的计数才能互相抵消。
        # ch  ：当前遍历到的【单个字符】（for 循环变量）
        #
        # ⚠️ 注意别把 d 和 ch 命名成同一个词——
        #    你在 E02 栽过（累加器叫 t 撞上字典 t → AttributeError）。
        #    本版 d 和 ch 分开，✅

        # ① 建一个空字典，s 和 t 共用
        d = {}

        # ② 遍历 s：每个字符的计数【加一】
        for ch in s:
            # .get(ch, 0)：ch 这个键【不存在】时返回默认值 0；
            #             存在时返回真实值。（不存在时 d[ch] 会 KeyError 崩）
            d[ch] = d.get(ch, 0) + 1

        # ③ 遍历 t：每个字符的计数【减一】
        for ch in t:
            d[ch] = d.get(ch, 0) - 1

            # ④ 【提前返回】只能在减一这半边判断
            #    计数变成负数 = t 里有 s 完全没有的字符 → 必然不是异位词
            if d[ch] < 0:
                return False

        # ⑤ 【最终判定】走完 t，字典里每个值都该是 0
        #    all(...)：所有元素都满足条件才返回 True
        #    ⚠️ 不能写成 if d.values(): —— 视图对象永远为真（静默错）
        return all(v == 0 for v in d.values())


# =============================================================================
# 【解法二】两个 dict 各数各的，直接比较
#
#    思路更直白，但多开一个字典。
#    交叉验证用：三种解法在所有用例上必须给出【相同结论】。
# =============================================================================
class Solution_两个字典:
    """解法二：s 和 t 各建一个字典，最后 d1 == d2 直接比较。"""

    def isAnagram(self, s: str, t: str) -> bool:
        d1 = {}
        d2 = {}
        for ch in s:
            d1[ch] = d1.get(ch, 0) + 1
        for ch in t:
            d2[ch] = d2.get(ch, 0) + 1
        # 两个字典相等 → 每个键的值都相等 → 字符多重集相同
        return d1 == d2


# =============================================================================
# 【解法三】26 格数组（依赖题目约束「只含小写字母」）
#
#    ⚠️ 这个方案【只能在题目保证的小写字母范围内用】。
#    换成中文/大写就会崩（负下标还会静默写错位置）。
#    你的「词频统计」作品统计中文 → 必须用 dict，不能用这个。
# =============================================================================
class Solution_26数组:
    """解法三：定长 26 数组。性能最好，但依赖题目约束。"""

    def isAnagram(self, s: str, t: str) -> bool:
        # 长度不等必然不是异位词（可选优化，O(n) 里省掉一半工作量）
        if len(s) != len(t):
            return False
        arr = [0] * 26          # 26 个格子 = 26 种【不同的字符种类】
        for ch in s:
            arr[ord(ch) - ord("a")] += 1
        for ch in t:
            arr[ord(ch) - ord("a")] -= 1
        return all(x == 0 for x in arr)


