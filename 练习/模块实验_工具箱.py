print("  [工具箱] 我被加载了！此刻 __name__ =", __name__)


def 算总价(菜价列表):
    """把一篮子菜的价格加起来"""
    return sum(菜价列表)


def 打包菜单(菜单):
    """把菜单列表拼成一行文字"""
    return ", ".join(菜单)


