# 4. 如果 配送工具.py 里把 函数名 写成了「生成配送单表」，
#    而你在 10.27练习_模块.py 里写的是「生成配送单」，
#    哪种 import 写法会**立刻**报错？哪种会**运行到才报错**？
#    写法一会马上报错，写法二要到运行才报错
#    【批改 ❌ 反了】正确答案是：
#      from 配送工具 import 生成配送单   → 立刻报错（ImportError）
#      import 配送工具 + 配送工具.生成配送单(...)  → 运行到才报错（AttributeError）
#    ⭐ 为什么？「from ... import 名字」里名字是明确写出来的，Python 一看就知道你要拿什么，
#    模块里没有 → 当场报错。而「import 模块」只说「把整个模块拿来」，
#    不检查你要用哪个函数，等真调用时才去模块里翻，翻不到才炸。
#    💼 真实项目：写法 A 少写一个字母 → 1 秒定位；写法 B 少写一个字母 → 跑半天到那行才炸。
